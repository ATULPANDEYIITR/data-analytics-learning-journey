WITH amount_statistics AS (
    SELECT
        percentile_cont(0.25)
            WITHIN GROUP (ORDER BY amount) AS q1,
        percentile_cont(0.75)
            WITHIN GROUP (ORDER BY amount) AS q3
    FROM orders
    WHERE amount > 0
)
INSERT INTO quality_issues
    (rule_name, table_name, record_key, severity, detail)
SELECT
    'amount_anomaly',
    'orders',
    o.order_id::TEXT,
    'HIGH',
    format(
        'Amount %s exceeds IQR upper fence %s.',
        o.amount,
        ROUND((s.q3 + 1.5 * (s.q3 - s.q1))::NUMERIC, 2)
    )
FROM orders AS o
CROSS JOIN amount_statistics AS s
WHERE o.amount > s.q3 + 1.5 * (s.q3 - s.q1);

SELECT
    severity,
    COUNT(*) AS issue_count
FROM quality_issues
GROUP BY severity
ORDER BY
    CASE severity
        WHEN 'CRITICAL' THEN 1
        WHEN 'HIGH' THEN 2
        WHEN 'MEDIUM' THEN 3
        WHEN 'LOW' THEN 4
        ELSE 5
    END;

SELECT *
FROM quality_issues
ORDER BY detected_at, issue_id;

-- =====================================================================
-- Transactional remediation example
-- =====================================================================

-- A duplicate should not be removed by arbitrary deletion. The remediation
-- below changes the duplicate record's email after an explicit review.
-- The transaction makes it possible to validate the postcondition and roll
-- back if the intended quality condition is not achieved.

BEGIN;

UPDATE customers
SET email = 'ravi.kumar.duplicate@example.com'
WHERE customer_id = 3
  AND lower(btrim(email)) = 'ravi@example.com';

DO $$
DECLARE
    remaining_duplicates INTEGER;
BEGIN
    SELECT COUNT(*)
    INTO remaining_duplicates
    FROM (
        SELECT
            lower(btrim(email)),
            lower(btrim(full_name))
        FROM customers
        WHERE email IS NOT NULL
        GROUP BY
            lower(btrim(email)),
            lower(btrim(full_name))
        HAVING COUNT(*) > 1
    ) AS duplicate_groups;

    IF remaining_duplicates > 0 THEN
        RAISE EXCEPTION
            'Duplicate validation failed after remediation.';
    END IF;
END
$$;

COMMIT;

-- Verify the remediation.
SELECT
    lower(btrim(email)) AS normalized_email,
    lower(btrim(full_name)) AS normalized_name,
    COUNT(*) AS occurrence_count
FROM customers
WHERE email IS NOT NULL
GROUP BY
    lower(btrim(email)),
    lower(btrim(full_name))
HAVING COUNT(*) > 1;

