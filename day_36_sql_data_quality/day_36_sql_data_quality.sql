-- =====================================================================
-- Completeness profiling
-- =====================================================================

CREATE OR REPLACE VIEW customer_completeness_profile AS
SELECT
    COUNT(*) AS total_customers,
    COUNT(full_name) AS populated_names,
    COUNT(email) AS populated_emails,
    COUNT(phone) AS populated_phones,
    COUNT(*) FILTER (
        WHERE full_name IS NULL
    ) AS missing_names,
    COUNT(*) FILTER (
        WHERE email IS NULL
    ) AS missing_emails,
    COUNT(*) FILTER (
        WHERE phone IS NULL
    ) AS missing_phones
FROM customers;

SELECT *
FROM customer_completeness_profile;

-- Field-level missing-value audit. A NULL email is not interchangeable with
-- a blank string, so both conditions are explicitly checked where necessary.
SELECT
    customer_id,
    'full_name' AS column_name
FROM customers
WHERE full_name IS NULL OR btrim(full_name) = ''

UNION ALL

SELECT
    customer_id,
    'email'
FROM customers
WHERE email IS NULL OR btrim(email) = ''

UNION ALL

SELECT
    customer_id,
    'phone'
FROM customers
WHERE phone IS NULL OR btrim(phone) = ''

ORDER BY customer_id, column_name;

-- =====================================================================
-- Duplicate detection
-- =====================================================================

-- Surrogate customer_id values cannot identify business duplicates.
-- Normalizing email and name makes the comparison insensitive to case and
-- accidental leading/trailing whitespace.
WITH duplicate_groups AS (
    SELECT
        lower(btrim(email)) AS normalized_email,
        lower(btrim(full_name)) AS normalized_name,
        COUNT(*) AS occurrence_count,
        ARRAY_AGG(customer_id ORDER BY customer_id) AS customer_ids
    FROM customers
    WHERE email IS NOT NULL
      AND btrim(email) <> ''
    GROUP BY
        lower(btrim(email)),
        lower(btrim(full_name))
    HAVING COUNT(*) > 1
)
SELECT
    normalized_email,
    normalized_name,
    occurrence_count,
    customer_ids
FROM duplicate_groups
ORDER BY occurrence_count DESC;

-- Detect duplicate emails even when the names differ. This is a separate
-- rule because an email collision and an identical business identity do not
-- necessarily mean the same thing.
SELECT
    lower(btrim(email)) AS normalized_email,
    COUNT(*) AS customer_count,
    ARRAY_AGG(customer_id ORDER BY customer_id) AS customer_ids
FROM customers
WHERE email IS NOT NULL
GROUP BY lower(btrim(email))
HAVING COUNT(*) > 1
ORDER BY customer_count DESC;

-- =====================================================================
-- Referential integrity
-- =====================================================================

-- PostgreSQL's foreign key prevents new invalid child rows. This query is
-- still useful for auditing legacy data imported while constraints were
-- disabled in another system.
SELECT
    o.order_id,
    o.customer_id
FROM orders AS o
LEFT JOIN customers AS c
    ON c.customer_id = o.customer_id
WHERE c.customer_id IS NULL;

