-- =====================================================================
-- Deterministic domain validation
-- =====================================================================

SELECT
    order_id,
    amount,
    order_date,
    status
FROM orders
WHERE amount <= 0
   OR order_date IS NULL
   OR status NOT IN (
        'pending',
        'paid',
        'cancelled',
        'refunded'
   );

-- =====================================================================
-- Anomaly detection with distribution statistics
-- =====================================================================

-- PostgreSQL percentile_cont calculates exact interpolated percentiles.
-- The IQR rule is appropriate when the distribution is skewed and extreme
-- values should be identified without assuming normality.
WITH amount_statistics AS (
    SELECT
        percentile_cont(0.25)
            WITHIN GROUP (ORDER BY amount) AS q1,
        percentile_cont(0.50)
            WITHIN GROUP (ORDER BY amount) AS median_amount,
        percentile_cont(0.75)
            WITHIN GROUP (ORDER BY amount) AS q3
    FROM orders
    WHERE amount > 0
),
bounds AS (
    SELECT
        q1,
        median_amount,
        q3,
        q3 - q1 AS iqr,
        q3 + 1.5 * (q3 - q1) AS upper_fence
    FROM amount_statistics
)
SELECT
    o.order_id,
    o.amount,
    b.q1,
    b.median_amount,
    b.q3,
    b.iqr,
    b.upper_fence,
    CASE
        WHEN o.amount > b.upper_fence THEN 'ANOMALY'
        ELSE 'NORMAL'
    END AS classification
FROM orders AS o
CROSS JOIN bounds AS b
ORDER BY o.amount DESC;

-- =====================================================================
-- Customer-relative anomaly detection
-- =====================================================================

-- A value can be normal globally but abnormal for one customer. Window
-- functions therefore calculate each customer's historical average and rank.
WITH customer_statistics AS (
    SELECT
        customer_id,
        order_id,
        amount,
        AVG(amount) OVER (
            PARTITION BY customer_id
        ) AS customer_average,
        COUNT(*) OVER (
            PARTITION BY customer_id
        ) AS customer_order_count,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY amount DESC
        ) AS amount_rank
    FROM orders
    WHERE status <> 'cancelled'
)
SELECT
    customer_id,
    order_id,
    amount,
    ROUND(customer_average, 2) AS customer_average,
    customer_order_count,
    amount_rank
FROM customer_statistics
WHERE amount > customer_average * 2
ORDER BY customer_id, amount DESC;

-- =====================================================================
-- Daily activity anomaly detection
-- =====================================================================

WITH daily_activity AS (
    SELECT
        customer_id,
        order_date,
        COUNT(*) AS daily_order_count
    FROM orders
    WHERE customer_id IS NOT NULL
    GROUP BY customer_id, order_date
),
activity_statistics AS (
    SELECT
        AVG(daily_order_count::NUMERIC) AS average_daily_orders,
        STDDEV_POP(daily_order_count::NUMERIC) AS stddev_daily_orders
    FROM daily_activity
)
SELECT
    d.customer_id,
    d.order_date,
    d.daily_order_count,
    ROUND(s.average_daily_orders, 2) AS average_daily_orders,
    ROUND(s.stddev_daily_orders, 2) AS stddev_daily_orders,
    CASE
        WHEN d.daily_order_count >
             s.average_daily_orders +
             3 * s.stddev_daily_orders
        THEN 'ANOMALY'
        ELSE 'NORMAL'
    END AS classification
FROM daily_activity AS d
CROSS JOIN activity_statistics AS s
ORDER BY d.daily_order_count DESC;

