-- SQL Data Quality Engineering
-- PostgreSQL-compatible demonstration.
--
-- The model represents a retail ingestion domain and deliberately includes
-- imperfect records so that each quality rule can be observed.
--
-- The four major quality dimensions are separated:
--   duplicate detection       -> business identity collisions
--   missing values            -> completeness failures
--   referential integrity     -> invalid parent-child relationships
--   anomaly detection         -> statistically unusual observations
--
-- Run this script in PostgreSQL.

DROP SCHEMA IF EXISTS sql_data_quality CASCADE;
CREATE SCHEMA sql_data_quality;
SET search_path TO sql_data_quality;

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT,
    email TEXT,
    phone TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT customers_name_not_blank
        CHECK (full_name IS NULL OR btrim(full_name) <> ''),

    CONSTRAINT customers_email_not_blank
        CHECK (email IS NULL OR btrim(email) <> '')
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT,
    amount NUMERIC(14, 2) NOT NULL,
    order_date DATE NOT NULL,
    status TEXT NOT NULL,

    CONSTRAINT orders_positive_amount
        CHECK (amount > 0),

    CONSTRAINT orders_valid_status
        CHECK (
            status IN (
                'pending',
                'paid',
                'cancelled',
                'refunded'
            )
        ),

    CONSTRAINT orders_customer_fk
        FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- This index supports normalized business-identity searches. It is not made
-- UNIQUE because the purpose of this demonstration is to detect historical
-- duplicates rather than prevent every future duplicate at ingestion time.
CREATE INDEX idx_customers_normalized_identity
    ON customers (
        lower(btrim(email)),
        lower(btrim(full_name))
    );

CREATE INDEX idx_orders_customer_date
    ON orders (customer_id, order_date);

CREATE INDEX idx_orders_amount
    ON orders (amount);

