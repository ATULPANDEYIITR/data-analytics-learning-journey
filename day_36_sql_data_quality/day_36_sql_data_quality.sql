-- =====================================================================
-- Data-quality governance principles represented by this schema
-- =====================================================================
--
-- A primary key prevents duplicate identifiers but cannot guarantee that two
-- customer records represent different real-world people.
--
-- NULL detection measures completeness, while CHECK constraints prevent some
-- classes of invalid values from entering the database.
--
-- A foreign key enforces structural integrity between parent and child data.
--
-- Statistical anomalies are not necessarily invalid records. An unusually
-- large order may be legitimate, so anomaly detection should normally create
-- an investigation signal rather than automatically delete the record.
--
-- Indexes improve repeated quality queries when their expressions and filter
-- predicates match the access patterns used by the workload.
