@dataclass
class PivotResult:
    """
    Stores the summarized cells of a Pivot Table.

    Each cell is identified by:
        row key
        column key

    Example:
        ("North",) + ("Laptop",)
    """

    cells: dict[tuple[Any, ...], dict[tuple[Any, ...], dict[str, Any]]]
    row_keys: list[tuple[Any, ...]]
    column_keys: list[tuple[Any, ...]]
    grand_totals: dict[str, Any]


# ---------------------------------------------------------------------------
# 10. PIVOT ENGINE
# ---------------------------------------------------------------------------

class PivotEngine:
    """
    A reusable Excel-style Pivot Table engine.

    This is not an attempt to reproduce Excel's internal implementation.
    Instead, it exposes the fundamental conceptual operations:

        source data
            ↓
        filters
            ↓
        dimensions
            ↓
        grouping
            ↓
        aggregation
            ↓
        summarized matrix
    """

    def __init__(self, records: list[SalesRecord]) -> None:
        self.records = records

    def validate_configuration(self, config: PivotConfiguration) -> None:
        if not config.values:
            raise ValueError(
                "A Pivot Table needs at least one value field "
                "for meaningful numeric summarization."
            )

        valid_fields = {
            "order_date",
            "region",
            "salesperson",
            "product",
            "category",
            "quantity",
            "unit_price",
            "unit_cost",
            "sales",
            "revenue",
            "cost",
            "profit",
            "profit_margin",
            "customer_type",
        }

        requested = (
            config.rows
            + config.columns
            + list(config.filters.keys())
            + [value.field for value in config.values]
        )

        unknown = [
            item for item in requested
            if item.lower().replace(" ", "_") not in valid_fields
            and item not in config.calculated_fields
        ]

        if unknown:
            raise ValueError(f"Unknown Pivot field(s): {unknown}")

    def calculate_value(
        self,
        record: SalesRecord,
        value_field_name: str,
        calculated_fields: dict[str, Callable[[SalesRecord], Any]],
    ) -> Any:
        if value_field_name in calculated_fields:
            return calculated_fields[value_field_name](record)

        return field_value(record, value_field_name)

    def build(
        self,
        config: PivotConfiguration,
        row_grouping: Optional[dict[str, str]] = None,
        column_grouping: Optional[dict[str, str]] = None,
        sort_rows: bool = True,
        sort_columns: bool = True,
    ) -> PivotResult:
        self.validate_configuration(config)

        row_grouping = row_grouping or {}
        column_grouping = column_grouping or {}

        records = apply_filters(self.records, config.filters)

        cells: dict[
            tuple[Any, ...],
            dict[tuple[Any, ...], dict[str, list[Any]]]
        ] = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))

        row_keys_set: set[tuple[Any, ...]] = set()
        column_keys_set: set[tuple[Any, ...]] = set()

        for record in records:
            row_key = tuple(
                grouped_value(
                    record,
                    field_name,
                    row_grouping.get(field_name),
                )
                for field_name in config.rows
            )

            column_key = tuple(
                grouped_value(
                    record,
                    field_name,
                    column_grouping.get(field_name),
                )
                for field_name in config.columns
            )

            row_keys_set.add(row_key)
            column_keys_set.add(column_key)

            for value_field in config.values:
                value = self.calculate_value(
                    record,
                    value_field.field,
                    config.calculated_fields,
                )

                cells[row_key][column_key][value_field.label].append(value)

        row_keys = sorted(row_keys_set) if sort_rows else list(row_keys_set)
        column_keys = (
            sorted(column_keys_set)
            if sort_columns
            else list(column_keys_set)
        )

        summarized: dict[
            tuple[Any, ...],
            dict[tuple[Any, ...], dict[str, Any]]
        ] = defaultdict(dict)

        for row_key in row_keys:
            for column_key in column_keys:
                raw_values = cells[row_key][column_key]

                if not raw_values:
                    continue

                summarized[row_key][column_key] = {}

                for value_field in config.values:
                    values = raw_values[value_field.label]
                    function = AGGREGATIONS[value_field.aggregation]
                    summarized[row_key][column_key][value_field.label] = function(
                        values
                    )

        grand_totals: dict[str, Any] = {}

        for value_field in config.values:
            all_values: list[Any] = []

            for row_cells in cells.values():
                for cell in row_cells.values():
                    all_values.extend(cell[value_field.label])

            function = AGGREGATIONS[value_field.aggregation]
            grand_totals[value_field.label] = function(all_values)

        return PivotResult(
            cells=dict(summarized),
            row_keys=row_keys,
            column_keys=column_keys,
            grand_totals=grand_totals,
        )


