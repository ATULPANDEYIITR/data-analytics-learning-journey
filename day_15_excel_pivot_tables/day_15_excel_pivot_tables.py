# 32. PERFORMANCE CONSIDERATIONS
# ---------------------------------------------------------------------------
#
# Let:
#   N = number of source records
#   R = number of distinct row keys
#   C = number of distinct column keys
#   V = number of value fields
#
# A straightforward pivot pass is approximately O(N * V) for constructing
# aggregates, plus sorting costs.
#
# Memory depends on:
#   - number of unique dimensions
#   - number of cells
#   - number of measures
#
# For large datasets, storing every raw value for every aggregation is less
# memory-efficient than maintaining streaming accumulators.
#
# The demonstration below shows a streaming SUM calculation.


def streaming_sum_by_dimension(
    records: Iterable[SalesRecord],
    dimension: str,
    measure: str,
) -> dict[Any, float]:
    totals: defaultdict[Any, float] = defaultdict(float)

    for record in records:
        key = field_value(record, dimension)
        value = field_value(record, measure)
        totals[key] += value

    return dict(totals)


