# ---------------------------------------------------------------------------
# 1. FUNDAMENTAL CONCEPTS
# ---------------------------------------------------------------------------
#
# A Pivot Table does not normally change the underlying source records.
# Instead, it creates a summarized view by:
#
#   1. Choosing dimensions for Rows.
#   2. Choosing dimensions for Columns.
#   3. Choosing one or more measures for Values.
#   4. Optionally restricting records with Filters.
#   5. Applying aggregation functions such as SUM or COUNT.
#
# Example:
#
# Rows    = Region
# Columns = Product
# Values  = Sales
#
# The result answers:
#
# "How much did each region sell for each product?"
#
# The raw records remain unchanged.


@dataclass
class SalesRecord:
    """A single normalized source-table row."""

    order_id: str
    order_date: date
    region: str
    salesperson: str
    product: str
    category: str
    quantity: int
    unit_price: float
    unit_cost: float
    customer_type: str

    @property
    def sales(self) -> float:
        """Revenue generated by this transaction."""
        return self.quantity * self.unit_price

    @property
    def cost(self) -> float:
        """Estimated product cost."""
        return self.quantity * self.unit_cost

    @property
    def profit(self) -> float:
        """Revenue minus cost."""
        return self.sales - self.cost

    @property
    def profit_margin(self) -> float:
        """Profit as a percentage of revenue."""
        if self.sales == 0:
            return 0.0
        return self.profit / self.sales


