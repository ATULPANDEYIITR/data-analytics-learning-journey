# 33. MEMORY-EFFICIENT AVERAGE
# ---------------------------------------------------------------------------
#
# Average can also be calculated without retaining every observation:
#
#     average = sum / count
#
# This is an important implementation technique for large datasets.


def streaming_average(
    values: Iterable[float],
) -> float:
    total = 0.0
    count = 0

    for value in values:
        total += value
        count += 1

    return total / count if count else 0.0


