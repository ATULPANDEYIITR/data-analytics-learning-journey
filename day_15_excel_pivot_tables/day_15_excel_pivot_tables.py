@dataclass
class ValueField:
    """
    Defines one field placed in Excel's Values area.

    Example:
        ValueField("Sales", "sum", "Total Sales")
    """

    field: str
    aggregation: str = "sum"
    label: Optional[str] = None

    def __post_init__(self) -> None:
        if self.aggregation not in AGGREGATIONS:
            raise ValueError(
                f"Unsupported aggregation '{self.aggregation}'. "
                f"Choose from: {', '.join(AGGREGATIONS)}"
            )

        if self.label is None:
            self.label = f"{self.aggregation.upper()} of {self.field}"


@dataclass
class PivotConfiguration:
    """
    Represents the logical architecture of a Pivot Table.

    rows:
        Fields used as row dimensions.

    columns:
        Fields used as column dimensions.

    values:
        Measures that are aggregated.

    filters:
        Record-level filtering rules.

    calculated_fields:
        Formula-like fields evaluated from each source record.
    """

    rows: list[str] = field(default_factory=list)
    columns: list[str] = field(default_factory=list)
    values: list[ValueField] = field(default_factory=list)
    filters: dict[str, set[Any]] = field(default_factory=dict)
    calculated_fields: dict[str, Callable[[SalesRecord], Any]] = field(
        default_factory=dict
    )


# ---------------------------------------------------------------------------
# 6. CALCULATED FIELDS
# ---------------------------------------------------------------------------
#
# An Excel calculated field creates a formula at the Pivot Table level.
#
# Example:
#
#   Profit = Sales - Cost
#
# This differs conceptually from simply adding a physical Profit column to
# the source table. Calculated fields operate through the Pivot Table's
# calculation model and have important Excel-specific limitations.
#
# The engine below models the useful conceptual behavior while keeping the
# implementation transparent.


def calculated_profit(record: SalesRecord) -> float:
    return record.sales - record.cost


def calculated_margin(record: SalesRecord) -> float:
    if record.sales == 0:
        return 0.0
    return record.profit / record.sales


def calculated_order_value_with_tax(record: SalesRecord) -> float:
    """Example calculated measure using a 18% illustrative tax rate."""
    return record.sales * 1.18


# ---------------------------------------------------------------------------
# 7. FILTERING
# ---------------------------------------------------------------------------

def apply_filters(
    records: Iterable[SalesRecord],
    filters: dict[str, set[Any]],
) -> list[SalesRecord]:
    """
    Apply Pivot-style report filters.

    Multiple allowed values for one field behave like OR.
    Different fields behave like AND.

    Example:
        Region in {"North", "South"}
        AND Customer Type == "Corporate"
    """
    filtered: list[SalesRecord] = []

    for record in records:
        accepted = True

        for field_name, allowed_values in filters.items():
            actual_value = field_value(record, field_name)

            if actual_value not in allowed_values:
                accepted = False
                break

        if accepted:
            filtered.append(record)

    return filtered


# ---------------------------------------------------------------------------
# 8. GROUPING
# ---------------------------------------------------------------------------

def month_group(value: date) -> str:
    """Group dates into calendar months."""
    return value.strftime("%Y-%m")


def quarter_group(value: date) -> str:
    """Group dates into calendar quarters."""
    quarter = (value.month - 1) // 3 + 1
    return f"{value.year}-Q{quarter}"


def year_group(value: date) -> int:
    """Group dates into calendar years."""
    return value.year


def quantity_band(quantity: int) -> str:
    """
    Numeric grouping example.

    Excel users can group numeric values into intervals.
    """
    if quantity <= 2:
        return "1-2"
    if quantity <= 5:
        return "3-5"
    if quantity <= 8:
        return "6-8"
    return "9+"


def grouped_value(
    record: SalesRecord,
    field_name: str,
    grouping: Optional[str] = None,
) -> Any:
    value = field_value(record, field_name)

    if grouping is None:
        return value

    if grouping == "month":
        if not isinstance(value, date):
            raise TypeError("Month grouping requires a date field.")
        return month_group(value)

    if grouping == "quarter":
        if not isinstance(value, date):
            raise TypeError("Quarter grouping requires a date field.")
        return quarter_group(value)

    if grouping == "year":
        if not isinstance(value, date):
            raise TypeError("Year grouping requires a date field.")
        return year_group(value)

    if grouping == "quantity_band":
        if not isinstance(value, int):
            raise TypeError("Quantity-band grouping requires an integer.")
        return quantity_band(value)

    raise ValueError(f"Unknown grouping mode: {grouping}")


