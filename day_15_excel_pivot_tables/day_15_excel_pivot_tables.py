def build_management_report(records: list[SalesRecord]) -> dict[str, Any]:
    """
    Build several Pivot-style management metrics from one source dataset.
    """

    total_sales = sum(record.sales for record in records)
    total_profit = sum(record.profit for record in records)
    total_quantity = sum(record.quantity for record in records)

    region_sales = streaming_sum_by_dimension(
        records,
        "region",
        "sales",
    )

    category_sales = streaming_sum_by_dimension(
        records,
        "category",
        "sales",
    )

    product_sales = streaming_sum_by_dimension(
        records,
        "product",
        "sales",
    )

    average_order_value = (
        total_sales / len(records)
        if records
        else 0.0
    )

    profit_margin = (
        total_profit / total_sales
        if total_sales
        else 0.0
    )

    return {
        "total_sales": total_sales,
        "total_profit": total_profit,
        "total_quantity": total_quantity,
        "transaction_count": len(records),
        "average_order_value": average_order_value,
        "profit_margin": profit_margin,
        "sales_by_region": region_sales,
        "sales_by_category": category_sales,
        "sales_by_product": product_sales,
    }


