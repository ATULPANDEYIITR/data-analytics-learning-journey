# 31. PIVOT ARCHITECTURE AS A DATA PIPELINE
# ---------------------------------------------------------------------------
#
# The important conceptual pipeline is:
#
#     source table
#          |
#          v
#       filtering
#          |
#          v
#       grouping keys
#          |
#          v
#      aggregation
#          |
#          v
#      Pivot cells
#          |
#          +----> subtotals
#          |
#          +----> grand totals
#          |
#          +----> drill-down
#
# This resembles a GROUP BY operation in SQL.
#
# SQL conceptual equivalent:
#
#     SELECT region, product, SUM(sales)
#     FROM sales
#     GROUP BY region, product;
#
# Pivot Tables provide a user-oriented multidimensional interface around
# related aggregation operations.


def sql_like_group_by(
    records: Iterable[SalesRecord],
    dimensions: list[str],
    measure: str,
) -> dict[tuple[Any, ...], float]:
    result: defaultdict[tuple[Any, ...], float] = defaultdict(float)

    for record in records:
        key = tuple(
            field_value(record, dimension)
            for dimension in dimensions
        )
        result[key] += field_value(record, measure)

    return dict(result)


