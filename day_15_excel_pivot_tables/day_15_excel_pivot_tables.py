# 3. BASIC AGGREGATION FUNCTIONS
# ---------------------------------------------------------------------------

def aggregate_sum(values: Iterable[float]) -> float:
    """Equivalent conceptually to Excel's SUM."""
    return sum(values)


def aggregate_count(values: Iterable[Any]) -> int:
    """Counts supplied records/values."""
    return sum(1 for _ in values)


def aggregate_average(values: Iterable[float]) -> float:
    """Equivalent conceptually to Excel's AVERAGE."""
    materialized = list(values)
    return mean(materialized) if materialized else 0.0


def aggregate_min(values: Iterable[float]) -> Optional[float]:
    """Equivalent conceptually to Excel's MIN."""
    materialized = list(values)
    return min(materialized) if materialized else None


def aggregate_max(values: Iterable[float]) -> Optional[float]:
    """Equivalent conceptually to Excel's MAX."""
    materialized = list(values)
    return max(materialized) if materialized else None


def aggregate_distinct_count(values: Iterable[Any]) -> int:
    """
    Conceptually similar to Excel Data Model / Power Pivot distinct count.
    A normal Pivot Table and a Data Model Pivot Table have different
    capabilities around distinct counting.
    """
    return len(set(values))


AGGREGATIONS: dict[str, Callable[[Iterable[Any]], Any]] = {
    "sum": aggregate_sum,
    "count": aggregate_count,
    "average": aggregate_average,
    "min": aggregate_min,
    "max": aggregate_max,
    "distinct_count": aggregate_distinct_count,
}


