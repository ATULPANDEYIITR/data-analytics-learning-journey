# 36. SAFE NUMERIC NORMALIZATION
# ---------------------------------------------------------------------------

def normalize_numeric(value: Any) -> Optional[float]:
    """
    Convert reasonable numeric input to float.

    This is analogous to cleaning imported spreadsheet data before building
    a Pivot Table.
    """
    if value is None:
        return None

    if isinstance(value, bool):
        return None

    if isinstance(value, (int, float)):
        return float(value)

    if isinstance(value, str):
        cleaned = value.strip().replace(",", "")

        if not cleaned:
            return None

        try:
            return float(cleaned)
        except ValueError:
            return None

    return None


