def subtotal_by_dimension(
    records: list[SalesRecord],
    dimension: str,
    measure: str = "sales",
) -> dict[Any, float]:
    totals: defaultdict[Any, float] = defaultdict(float)

    for record in records:
        totals[field_value(record, dimension)] += field_value(record, measure)

    return dict(totals)


