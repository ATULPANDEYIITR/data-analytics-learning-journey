def field_value(record: SalesRecord, field_name: str) -> Any:
    """
    Converts a Pivot Table field name into a value from the source record.

    This resembles Excel's field model:
        Region
        Product
        Sales
        Profit
        Quantity
        Order Date
    """
    normalized = field_name.strip().lower().replace(" ", "_")

    aliases = {
        "order_date": "order_date",
        "region": "region",
        "salesperson": "salesperson",
        "product": "product",
        "category": "category",
        "quantity": "quantity",
        "unit_price": "unit_price",
        "unit_cost": "unit_cost",
        "sales": "sales",
        "revenue": "sales",
        "cost": "cost",
        "profit": "profit",
        "profit_margin": "profit_margin",
        "customer_type": "customer_type",
    }

    if normalized not in aliases:
        raise KeyError(f"Unknown Pivot field: {field_name}")

    return getattr(record, aliases[normalized])


