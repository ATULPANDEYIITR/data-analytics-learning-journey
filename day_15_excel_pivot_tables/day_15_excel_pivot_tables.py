def format_number(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:,.2f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def print_pivot(result: PivotResult, title: str) -> None:
    print("\n" + "=" * 90)
    print(title)
    print("=" * 90)

    if not result.row_keys:
        print("No rows matched the selected filters.")
        return

    if not result.column_keys:
        print("No columns matched the selected filters.")
        return

    print("Rows:", result.row_keys)
    print("Columns:", result.column_keys)

    for row_key in result.row_keys:
        print(f"\nRow: {row_key}")

        row_cells = result.cells.get(row_key, {})

        for column_key in result.column_keys:
            cell = row_cells.get(column_key)

            if cell is None:
                print(f"  {column_key}: no records")
            else:
                values = ", ".join(
                    f"{label}={format_number(value)}"
                    for label, value in cell.items()
                )
                print(f"  {column_key}: {values}")

    print("\nGrand Totals:")
    for label, value in result.grand_totals.items():
        print(f"  {label}: {format_number(value)}")


