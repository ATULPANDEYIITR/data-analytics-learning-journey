# 29. VALIDATION
# ---------------------------------------------------------------------------
#
# A Pivot Table is only as reliable as the source data.
#
# Common source-data problems:
#   - Duplicate records
#   - Incorrect headers
#   - Mixed data types
#   - Blank categories
#   - Numbers stored as text
#   - Dates stored as text
#   - Inconsistent spellings
#   - Formula errors
#
# The validator below demonstrates basic checks.


def validate_source(records: list[SalesRecord]) -> list[str]:
    errors: list[str] = []

    order_ids: set[str] = set()

    for record in records:
        if not record.order_id:
            errors.append("A record has a blank order ID.")

        if record.order_id in order_ids:
            errors.append(f"Duplicate order ID: {record.order_id}")

        order_ids.add(record.order_id)

        if record.quantity < 0:
            errors.append(
                f"Negative quantity for {record.order_id}."
            )

        if record.unit_price < 0:
            errors.append(
                f"Negative unit price for {record.order_id}."
            )

        if record.unit_cost < 0:
            errors.append(
                f"Negative unit cost for {record.order_id}."
            )

        if not record.region:
            errors.append(
                f"Blank region for {record.order_id}."
            )

    return errors


