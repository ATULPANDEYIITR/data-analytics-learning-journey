-- ------------------------------------------------------------
-- CALCULATED COLUMN EQUIVALENTS
-- ------------------------------------------------------------
-- DAX calculated columns are stored model columns evaluated
-- during model processing or refresh.
--
-- This SQL view calculates equivalent expressions at query time.

CREATE OR REPLACE VIEW vw_sales_calculated_columns AS
SELECT
    s.sale_id,
    s.product_id,
    p.product_name,
    c.category_name,
    s.sale_date,
    s.quantity,
    p.unit_price,
    s.unit_cost,

    p.unit_price * s.quantity AS revenue,

    s.unit_cost * s.quantity AS total_cost,

    (p.unit_price - s.unit_cost) * s.quantity AS profit,

    CASE
        WHEN p.unit_price > s.unit_cost * 1.5
            THEN 'High'
        ELSE 'Standard'
    END AS profitability

FROM fact_sales s
JOIN dim_product p
    ON p.product_id = s.product_id
JOIN dim_category c
    ON c.category_id = p.category_id;

-- ------------------------------------------------------------
-- MEASURE EQUIVALENTS
-- ------------------------------------------------------------
-- These views calculate reusable aggregations.
-- Their results respond to query filters, similar to measures
-- responding to report filter context.

CREATE OR REPLACE VIEW vw_sales_measures AS
SELECT
    c.category_id,
    c.category_name,

    SUM(p.unit_price * s.quantity) AS total_sales,

    SUM(s.unit_cost * s.quantity) AS total_cost,

    SUM(
        (p.unit_price - s.unit_cost) * s.quantity
    ) AS total_profit,

    SUM(s.quantity) AS total_quantity,

    COUNT(*) AS transaction_count,

    CASE
        WHEN SUM(p.unit_price * s.quantity) = 0
            THEN NULL
        ELSE
            100.0 * SUM(
                (p.unit_price - s.unit_cost) * s.quantity
            ) / SUM(p.unit_price * s.quantity)
    END AS profit_margin

FROM fact_sales s
JOIN dim_product p
    ON p.product_id = s.product_id
JOIN dim_category c
    ON c.category_id = p.category_id

GROUP BY
    c.category_id,
    c.category_name;

-- ------------------------------------------------------------
-- CALCULATED TABLE EQUIVALENT
-- ------------------------------------------------------------
-- A materialized view stores the calculated result.
-- Refresh is required when source data changes.

CREATE MATERIALIZED VIEW IF NOT EXISTS mv_category_summary AS
SELECT
    c.category_id,
    c.category_name,
    COUNT(p.product_id) AS product_count,
    COALESCE(AVG(p.unit_price), 0) AS average_product_price,
    COALESCE(SUM(p.unit_price), 0) AS combined_list_price

FROM dim_category c
LEFT JOIN dim_product p
    ON p.category_id = c.category_id

GROUP BY
    c.category_id,
    c.category_name;

CREATE UNIQUE INDEX IF NOT EXISTS idx_mv_category_summary_id
    ON mv_category_summary(category_id);

-- ------------------------------------------------------------
-- CALCULATE-LIKE FUNCTION
-- ------------------------------------------------------------
-- Demonstrates replacement of a category filter.
-- Passing NULL means all categories.
--
-- Unlike DAX CALCULATE, this function exposes only an explicit
-- parameterized SQL filtering interface.

CREATE OR REPLACE FUNCTION fn_category_sales(
    p_category_name VARCHAR DEFAULT NULL
)
RETURNS TABLE (
    category_name VARCHAR,
    total_sales NUMERIC,
    total_quantity BIGINT,
    total_profit NUMERIC
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        c.category_name::VARCHAR,

        COALESCE(
            SUM(p.unit_price * s.quantity),
            0
        )::NUMERIC,

        COALESCE(
            SUM(s.quantity),
            0
        )::BIGINT,

        COALESCE(
            SUM((p.unit_price - s.unit_cost) * s.quantity),
            0
        )::NUMERIC

    FROM dim_category c
    LEFT JOIN dim_product p
        ON p.category_id = c.category_id
    LEFT JOIN fact_sales s
        ON s.product_id = p.product_id

    WHERE
        p_category_name IS NULL
        OR c.category_name = p_category_name

    GROUP BY c.category_name
    ORDER BY c.category_name;
$$;

-- ------------------------------------------------------------
-- SUMX-LIKE FUNCTION
-- ------------------------------------------------------------
-- Iterates through each eligible transaction and calculates
-- an expression before summing the individual results.

CREATE OR REPLACE FUNCTION fn_sumx_revenue(
    p_category_name VARCHAR DEFAULT NULL
)
RETURNS NUMERIC
LANGUAGE SQL
STABLE
AS $$
    SELECT COALESCE(
        SUM(p.unit_price * s.quantity),
        0
    )
    FROM fact_sales s
    JOIN dim_product p
        ON p.product_id = s.product_id
    JOIN dim_category c
        ON c.category_id = p.category_id
    WHERE
        p_category_name IS NULL
        OR c.category_name = p_category_name;
$$;

-- ------------------------------------------------------------
-- FILTER-LIKE QUERY FUNCTION
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_high_value_sales(
    p_minimum_revenue NUMERIC
)
RETURNS TABLE (
    sale_id BIGINT,
    product_name VARCHAR,
    revenue NUMERIC,
    profit NUMERIC
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        s.sale_id,
        p.product_name::VARCHAR,
        (p.unit_price * s.quantity)::NUMERIC,
        ((p.unit_price - s.unit_cost) * s.quantity)::NUMERIC

    FROM fact_sales s
    JOIN dim_product p
        ON p.product_id = s.product_id

    WHERE p.unit_price * s.quantity >= p_minimum_revenue

    ORDER BY revenue DESC, s.sale_id;
$$;

-- ------------------------------------------------------------
-- DISTINCTCOUNT AND VALUES EQUIVALENTS
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW vw_category_values AS
SELECT DISTINCT
    category_name
FROM dim_category;

CREATE OR REPLACE VIEW vw_distinct_product_counts AS
SELECT
    c.category_name,
    COUNT(DISTINCT p.product_id) AS distinct_products

FROM dim_category c
LEFT JOIN dim_product p
    ON p.category_id = c.category_id

GROUP BY c.category_name;

-- ------------------------------------------------------------
-- MONTHLY AGGREGATION
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW vw_monthly_sales AS
SELECT
    d.calendar_year,
    d.calendar_month,
    d.month_name,

    SUM(p.unit_price * s.quantity) AS total_sales,

    SUM(s.unit_cost * s.quantity) AS total_cost,

    SUM(
        (p.unit_price - s.unit_cost) * s.quantity
    ) AS total_profit,

    SUM(s.quantity) AS total_quantity

FROM fact_sales s
JOIN dim_date d
    ON d.date_key = s.sale_date
JOIN dim_product p
    ON p.product_id = s.product_id

GROUP BY
    d.calendar_year,
    d.calendar_month,
    d.month_name;

-- ------------------------------------------------------------
-- QUERY: ALL-LIKE FILTER REMOVAL
-- ------------------------------------------------------------
-- The category condition is omitted to calculate the total
-- across all categories.

CREATE OR REPLACE VIEW vw_all_category_sales AS
SELECT
    SUM(p.unit_price * s.quantity) AS all_category_sales
FROM fact_sales s
JOIN dim_product p
    ON p.product_id = s.product_id;

-- ------------------------------------------------------------
-- QUERY: CONDITIONAL AGGREGATION
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW vw_product_performance AS
SELECT
    p.product_id,
    p.product_name,
    c.category_name,

    COALESCE(SUM(s.quantity), 0) AS quantity_sold,

    COALESCE(
        SUM(p.unit_price * s.quantity),
        0
    ) AS revenue,

    COALESCE(
        SUM((p.unit_price - s.unit_cost) * s.quantity),
        0
    ) AS profit,

    COUNT(s.sale_id) AS transaction_count

FROM dim_product p
JOIN dim_category c
    ON c.category_id = p.category_id
LEFT JOIN fact_sales s
    ON s.product_id = p.product_id

GROUP BY
    p.product_id,
    p.product_name,
    c.category_name;

-- ------------------------------------------------------------
-- DATA VALIDATION FUNCTION
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_validate_sales()
RETURNS TABLE (
    sale_id BIGINT,
    validation_status TEXT,
    validation_message TEXT
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        s.sale_id,

        CASE
            WHEN s.quantity < 0 OR s.unit_cost < 0
                THEN 'INVALID'
            ELSE 'VALID'
        END,

        CASE
            WHEN s.quantity < 0
                THEN 'Negative quantity'
            WHEN s.unit_cost < 0
                THEN 'Negative unit cost'
            ELSE 'All checks passed'
        END

    FROM fact_sales s
    ORDER BY s.sale_id;
$$;

