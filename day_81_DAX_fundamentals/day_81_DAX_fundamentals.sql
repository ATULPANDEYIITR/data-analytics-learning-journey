-- SECURITY AND OPERATIONAL NOTES
-- ------------------------------------------------------------
-- Production deployment considerations:
--
-- 1. Use a dedicated database role with minimum privileges.
-- 2. Do not expose unrestricted table access to report users.
-- 3. Use PostgreSQL row-level security when data ownership
--    or tenant separation is required.
-- 4. Parameterize application queries.
-- 5. Refresh materialized views according to data freshness
--    requirements.
-- 6. Use EXPLAIN ANALYZE to evaluate query plans.
-- 7. Avoid treating SQL views as stored DAX calculated columns.
-- 8. Define date, currency, and rounding policies explicitly.
-- 9. Apply controlled migrations to production schemas.
-- 10. Monitor materialized-view refresh duration and locks.
