DECLARE
    v_sales NUMERIC;
    v_cost NUMERIC;
    v_profit NUMERIC;
    v_quantity BIGINT;
BEGIN
    SELECT
        SUM(p.unit_price * s.quantity),
        SUM(s.unit_cost * s.quantity),
        SUM((p.unit_price - s.unit_cost) * s.quantity),
        SUM(s.quantity)
    INTO
        v_sales,
        v_cost,
