-- ============================================================
-- DAX FUNDAMENTALS: POSTGRESQL ANALYTICAL DATA MODEL
-- ============================================================
-- Models a sales star schema and implements SQL equivalents
-- of selected analytical operations.
--
-- Concepts:
-- 1. Measures and aggregations
-- 2. Calculated-column equivalents
-- 3. Calculated-table equivalents
-- 4. Filter context through WHERE and GROUP BY
-- 5. Row context through row-level expressions
-- 6. Context transition through correlated evaluation
-- 7. CALCULATE-like filter replacement and filter removal
-- 8. SUMX-like row-by-row aggregation
--
-- SQL is not DAX. These implementations demonstrate related
-- analytical behavior without claiming identical semantics.
--
-- Target: PostgreSQL 14+
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS dax_fundamentals;

SET search_path TO dax_fundamentals, public;

-- ------------------------------------------------------------
-- DIMENSION TABLES
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS dim_category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(80) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS dim_product (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(120) NOT NULL UNIQUE,
    category_id INTEGER NOT NULL
        REFERENCES dim_category(category_id),
    unit_price NUMERIC(14, 2) NOT NULL
        CHECK (unit_price >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dim_date (
    date_key DATE PRIMARY KEY,
    calendar_year INTEGER NOT NULL,
    calendar_month INTEGER NOT NULL
        CHECK (calendar_month BETWEEN 1 AND 12),
    month_name VARCHAR(12) NOT NULL,
    quarter_number INTEGER NOT NULL
        CHECK (quarter_number BETWEEN 1 AND 4)
);

-- ------------------------------------------------------------
-- FACT TABLE
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS fact_sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL
        REFERENCES dim_product(product_id),
    sale_date DATE NOT NULL
        REFERENCES dim_date(date_key),
    quantity INTEGER NOT NULL
        CHECK (quantity >= 0),
    unit_cost NUMERIC(14, 2) NOT NULL
        CHECK (unit_cost >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A sale may have zero quantity, but it remains a transaction.
-- This distinction matters when comparing SUM with COUNT.

-- ------------------------------------------------------------
-- INDEXES
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_sales_date
    ON fact_sales(sale_date);

CREATE INDEX IF NOT EXISTS idx_sales_product_date
    ON fact_sales(product_id, sale_date);

CREATE INDEX IF NOT EXISTS idx_product_category
    ON dim_product(category_id);

CREATE INDEX IF NOT EXISTS idx_sales_positive_quantity
    ON fact_sales(sale_date)
    WHERE quantity > 0;

