CREATE TABLE IF NOT EXISTS bi_source.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(150) NOT NULL,
    region VARCHAR(50) NOT NULL,
    customer_segment VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_customer_name
        CHECK (length(trim(customer_name)) > 0),

    CONSTRAINT valid_customer_region
        CHECK (region IN ('North', 'South', 'East', 'West')),

    CONSTRAINT valid_customer_segment
        CHECK (
            customer_segment IN (
                'Enterprise',
                'Consumer',
                'Small Business'
            )
        )
);

CREATE TABLE IF NOT EXISTS bi_source.products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(150) NOT NULL,
    category VARCHAR(80) NOT NULL,
    unit_cost NUMERIC(14,2) NOT NULL,

    CONSTRAINT valid_product_name
        CHECK (length(trim(product_name)) > 0),

    CONSTRAINT nonnegative_product_cost
        CHECK (unit_cost >= 0)
);

CREATE TABLE IF NOT EXISTS bi_source.sales_transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL
        REFERENCES bi_source.customers(customer_id),

    product_id BIGINT NOT NULL
        REFERENCES bi_source.products(product_id),

    transaction_date DATE NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(14,2) NOT NULL,

    source_system VARCHAR(50) NOT NULL DEFAULT 'ERP',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_quantity
        CHECK (quantity > 0),

    CONSTRAINT nonnegative_unit_price
        CHECK (unit_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_source_sales_date
    ON bi_source.sales_transactions(transaction_date);

CREATE INDEX IF NOT EXISTS idx_source_sales_customer
    ON bi_source.sales_transactions(customer_id);

CREATE INDEX IF NOT EXISTS idx_source_sales_product
    ON bi_source.sales_transactions(product_id);

