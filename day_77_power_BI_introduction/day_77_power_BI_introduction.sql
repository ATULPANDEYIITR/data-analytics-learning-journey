-- 10. ETL PROCEDURE
-- ============================================================

CREATE OR REPLACE PROCEDURE bi_warehouse.refresh_sales()
LANGUAGE plpgsql
AS $$
DECLARE
    v_refresh_id BIGINT;
    v_count INTEGER;
BEGIN

    INSERT INTO bi_warehouse.refresh_history (
        process_name,
        status
    )
    VALUES (
        'SALES_WAREHOUSE_REFRESH',
        'RUNNING'
    )
    RETURNING refresh_id INTO v_refresh_id;

    BEGIN

        -- Update the current customer dimension.
        INSERT INTO bi_warehouse.dim_customer (
            customer_id,
            customer_name,
            region,
            customer_segment,
            is_current
        )
        SELECT
            customer_id,
            customer_name,
            region,
            customer_segment,
            TRUE
        FROM bi_source.customers
        ON CONFLICT (customer_id) DO UPDATE
        SET customer_name = EXCLUDED.customer_name,
            region = EXCLUDED.region,
            customer_segment = EXCLUDED.customer_segment;

        INSERT INTO bi_warehouse.dim_product (
            product_id,
            product_name,
            category,
            unit_cost
        )
        SELECT
            product_id,
            product_name,
            category,
            unit_cost
        FROM bi_source.products
        ON CONFLICT (product_id) DO UPDATE
        SET product_name = EXCLUDED.product_name,
            category = EXCLUDED.category,
            unit_cost = EXCLUDED.unit_cost;

        -- Ensure all source dates exist in the date dimension.
        INSERT INTO bi_warehouse.dim_date (
            date_key,
            full_date,
            calendar_year,
            calendar_quarter,
            calendar_month,
            month_name,
            day_of_month,
            day_of_week
        )
        SELECT DISTINCT
            TO_CHAR(transaction_date, 'YYYYMMDD')::INTEGER,
            transaction_date,
            EXTRACT(YEAR FROM transaction_date)::INTEGER,
            EXTRACT(QUARTER FROM transaction_date)::INTEGER,
            EXTRACT(MONTH FROM transaction_date)::INTEGER,
            TO_CHAR(transaction_date, 'FMMonth'),
            EXTRACT(DAY FROM transaction_date)::INTEGER,
            EXTRACT(ISODOW FROM transaction_date)::INTEGER
        FROM bi_source.sales_transactions
        ON CONFLICT (date_key) DO NOTHING;

        -- Upsert fact rows to support repeatable refreshes.
        INSERT INTO bi_warehouse.fact_sales (
            transaction_id,
            customer_key,
            product_key,
            date_key,
            quantity,
            unit_price,
            cost_amount
        )
        SELECT
            source.transaction_id,
            customer.customer_key,
            product.product_key,
            dates.date_key,
            source.quantity,
            source.unit_price,
            source.quantity * product.unit_cost
        FROM bi_source.sales_transactions source

        JOIN bi_warehouse.dim_customer customer
            ON customer.customer_id = source.customer_id

        JOIN bi_warehouse.dim_product product
            ON product.product_id = source.product_id

        JOIN bi_warehouse.dim_date dates
            ON dates.full_date = source.transaction_date

        ON CONFLICT (transaction_id) DO UPDATE
        SET customer_key = EXCLUDED.customer_key,
            product_key = EXCLUDED.product_key,
            date_key = EXCLUDED.date_key,
            quantity = EXCLUDED.quantity,
            unit_price = EXCLUDED.unit_price,
            cost_amount = EXCLUDED.cost_amount;

        GET DIAGNOSTICS v_count = ROW_COUNT;

        UPDATE bi_warehouse.refresh_history
        SET status = 'SUCCEEDED',
            completed_at = CURRENT_TIMESTAMP,
            records_processed = v_count
        WHERE refresh_id = v_refresh_id;

    EXCEPTION WHEN OTHERS THEN

        UPDATE bi_warehouse.refresh_history
        SET status = 'FAILED',
            completed_at = CURRENT_TIMESTAMP,
            error_message = SQLERRM
        WHERE refresh_id = v_refresh_id;

        RAISE;
    END;
END;
$$;

