CREATE OR REPLACE VIEW bi_reporting.vw_sales_analysis AS
SELECT
    f.transaction_id,
    d.full_date,
    d.calendar_year,
    d.calendar_quarter,
    d.calendar_month,
    d.month_name,
    c.customer_id,
    c.customer_name,
    c.region,
    c.customer_segment,
    p.product_id,
    p.product_name,
    p.category,
    f.quantity,
    f.unit_price,
    f.revenue,
    f.cost_amount,
    f.profit,

    CASE
        WHEN f.revenue = 0 THEN 0
        ELSE ROUND(
            f.profit / f.revenue * 100,
            2
        )
    END AS profit_margin_percent

FROM bi_warehouse.fact_sales f

JOIN bi_warehouse.dim_customer c
    ON c.customer_key = f.customer_key

JOIN bi_warehouse.dim_product p
    ON p.product_key = f.product_key

JOIN bi_warehouse.dim_date d
    ON d.date_key = f.date_key;

CREATE OR REPLACE VIEW bi_reporting.vw_dashboard_kpis AS
SELECT
    COUNT(*) AS total_transactions,

    COUNT(DISTINCT customer_id) AS unique_customers,

    SUM(quantity) AS total_units_sold,

    SUM(revenue) AS total_revenue,

    SUM(cost_amount) AS total_cost,

    SUM(profit) AS total_profit,

    CASE
        WHEN SUM(revenue) = 0 THEN 0
        ELSE ROUND(
            SUM(profit) / SUM(revenue) * 100,
            2
        )
    END AS profit_margin_percent,

    CASE
        WHEN COUNT(*) = 0 THEN 0
        ELSE ROUND(
            SUM(revenue) / COUNT(*),
            2
        )
    END AS average_order_value

FROM bi_reporting.vw_sales_analysis;

CREATE OR REPLACE VIEW bi_reporting.vw_regional_sales AS
SELECT
    region,
    COUNT(*) AS transaction_count,
    SUM(revenue) AS total_revenue,
    SUM(profit) AS total_profit,
    COUNT(DISTINCT customer_id) AS customer_count
FROM bi_reporting.vw_sales_analysis
GROUP BY region;

CREATE OR REPLACE VIEW bi_reporting.vw_product_performance AS
SELECT
    product_name,
    category,
    SUM(quantity) AS units_sold,
    SUM(revenue) AS total_revenue,
    SUM(profit) AS total_profit
FROM bi_reporting.vw_sales_analysis
GROUP BY product_name, category;

CREATE OR REPLACE VIEW bi_reporting.vw_monthly_sales AS
SELECT
    calendar_year,
    calendar_month,
    month_name,
    SUM(revenue) AS total_revenue,
    SUM(profit) AS total_profit
FROM bi_reporting.vw_sales_analysis
GROUP BY calendar_year, calendar_month, month_name;

