-- Revenue by region.
SELECT
    region,
    SUM(revenue) AS revenue,
    SUM(profit) AS profit,
    ROUND(
        SUM(profit) / NULLIF(SUM(revenue), 0) * 100,
        2
    ) AS profit_margin
FROM bi_reporting.vw_sales_analysis
GROUP BY region
ORDER BY revenue DESC;

-- Monthly growth evaluation.
WITH monthly AS (
    SELECT
        calendar_year,
        calendar_month,
        SUM(revenue) AS revenue
    FROM bi_reporting.vw_sales_analysis
    GROUP BY calendar_year, calendar_month
),
growth AS (
    SELECT
        calendar_year,
        calendar_month,
        revenue,
        LAG(revenue) OVER (
            ORDER BY calendar_year, calendar_month
        ) AS previous_revenue
    FROM monthly
)
SELECT
    calendar_year,
    calendar_month,
    revenue,
    previous_revenue,
    CASE
        WHEN previous_revenue IS NULL
          OR previous_revenue = 0 THEN NULL
        ELSE ROUND(
            (revenue - previous_revenue)
            / previous_revenue * 100,
            2
        )
    END AS growth_percent
FROM growth
ORDER BY calendar_year, calendar_month;

