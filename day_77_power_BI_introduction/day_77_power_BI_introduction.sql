CREATE OR REPLACE FUNCTION bi_governance.publish_report(
    p_report_id BIGINT,
    p_reviewer_id BIGINT
)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    v_status VARCHAR(20);
    v_reviewer_active BOOLEAN;
BEGIN

    SELECT active
    INTO v_reviewer_active
    FROM bi_governance.users
    WHERE user_id = p_reviewer_id;

    IF NOT FOUND OR NOT v_reviewer_active THEN
        RAISE EXCEPTION 'Reviewer is not active.';
    END IF;

    SELECT status
    INTO v_status
    FROM bi_governance.reports
    WHERE report_id = p_report_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Report does not exist.';
    END IF;

    IF v_status <> 'IN_REVIEW' THEN
        RAISE EXCEPTION 'Report must be IN_REVIEW.';
    END IF;

    INSERT INTO bi_governance.report_reviews (
        report_id,
        reviewer_id,
        review_decision,
        review_comment
    )
    VALUES (
        p_report_id,
        p_reviewer_id,
        'APPROVED',
        'Publication approved after report validation.'
    );

    UPDATE bi_governance.reports
