-- 3. DIMENSION TABLES
-- ============================================================

CREATE TABLE IF NOT EXISTS bi_warehouse.dim_customer (
    customer_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL UNIQUE,

    customer_name VARCHAR(150) NOT NULL,
    region VARCHAR(50) NOT NULL,
    customer_segment VARCHAR(50) NOT NULL,

    effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_to TIMESTAMPTZ,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT valid_customer_effective_period
        CHECK (
            effective_to IS NULL
            OR effective_to > effective_from
        )
);

CREATE TABLE IF NOT EXISTS bi_warehouse.dim_product (
    product_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL UNIQUE,

    product_name VARCHAR(150) NOT NULL,
    category VARCHAR(80) NOT NULL,
    unit_cost NUMERIC(14,2) NOT NULL,

    CONSTRAINT warehouse_nonnegative_cost
        CHECK (unit_cost >= 0)
);

CREATE TABLE IF NOT EXISTS bi_warehouse.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    calendar_year INTEGER NOT NULL,
    calendar_quarter INTEGER NOT NULL,
    calendar_month INTEGER NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    day_of_month INTEGER NOT NULL,
    day_of_week INTEGER NOT NULL,

    CONSTRAINT valid_date_key
        CHECK (
            date_key = (
                EXTRACT(YEAR FROM full_date)::INTEGER * 10000
                + EXTRACT(MONTH FROM full_date)::INTEGER * 100
                + EXTRACT(DAY FROM full_date)::INTEGER
            )
        ),

    CONSTRAINT valid_calendar_quarter
        CHECK (calendar_quarter BETWEEN 1 AND 4),

    CONSTRAINT valid_calendar_month
        CHECK (calendar_month BETWEEN 1 AND 12),

    CONSTRAINT valid_day_of_month
        CHECK (day_of_month BETWEEN 1 AND 31)
);

-- ============================================================
-- 4. FACT TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS bi_warehouse.fact_sales (
    sales_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    transaction_id BIGINT NOT NULL UNIQUE,

    customer_key BIGINT NOT NULL
        REFERENCES bi_warehouse.dim_customer(customer_key),

    product_key BIGINT NOT NULL
        REFERENCES bi_warehouse.dim_product(product_key),

    date_key INTEGER NOT NULL
        REFERENCES bi_warehouse.dim_date(date_key),

    quantity INTEGER NOT NULL,

    unit_price NUMERIC(14,2) NOT NULL,

    revenue NUMERIC(16,2)
        GENERATED ALWAYS AS (quantity * unit_price) STORED,

    cost_amount NUMERIC(16,2) NOT NULL,

    profit NUMERIC(16,2)
        GENERATED ALWAYS AS (
            quantity * unit_price - cost_amount
        ) STORED,

    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_fact_quantity
        CHECK (quantity > 0),

    CONSTRAINT valid_fact_price
        CHECK (unit_price >= 0),

    CONSTRAINT valid_fact_cost
        CHECK (cost_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_fact_sales_date
    ON bi_warehouse.fact_sales(date_key);

CREATE INDEX IF NOT EXISTS idx_fact_sales_customer
    ON bi_warehouse.fact_sales(customer_key);

CREATE INDEX IF NOT EXISTS idx_fact_sales_product
    ON bi_warehouse.fact_sales(product_key);

CREATE INDEX IF NOT EXISTS idx_fact_sales_customer_date
    ON bi_warehouse.fact_sales(customer_key, date_key);

