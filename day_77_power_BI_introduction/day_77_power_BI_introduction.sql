-- 7. REPORT STATE TRANSITION ENFORCEMENT
-- ============================================================

CREATE OR REPLACE FUNCTION bi_governance.validate_report_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    IF NEW.status = OLD.status THEN
        RETURN NEW;
    END IF;

    IF OLD.status = 'DRAFT'
       AND NEW.status = 'IN_REVIEW' THEN
        NULL;

    ELSIF OLD.status = 'IN_REVIEW'
       AND NEW.status IN ('APPROVED', 'REJECTED') THEN
        NULL;

    ELSIF OLD.status = 'APPROVED'
       AND NEW.status = 'PUBLISHED' THEN
        NULL;

    ELSIF OLD.status = 'REJECTED'
       AND NEW.status = 'DRAFT' THEN
        NULL;

    ELSIF OLD.status = 'PUBLISHED'
       AND NEW.status = 'DRAFT' THEN
        NULL;

    ELSE
        RAISE EXCEPTION
            'Invalid report transition: % -> %',
            OLD.status,
            NEW.status;
    END IF;

    NEW.updated_at = CURRENT_TIMESTAMP;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_report_transition
ON bi_governance.reports;

CREATE TRIGGER trg_report_transition
BEFORE UPDATE OF status
ON bi_governance.reports
FOR EACH ROW
EXECUTE FUNCTION bi_governance.validate_report_transition();

