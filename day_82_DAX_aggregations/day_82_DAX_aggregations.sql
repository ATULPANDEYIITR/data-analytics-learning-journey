-- ============================================================================
-- 5. AGGREGATION FUNCTIONS
-- ============================================================================

-- SUM equivalent.
CREATE OR REPLACE FUNCTION dax_sum_revenue(
    p_region VARCHAR DEFAULT NULL,
    p_category VARCHAR DEFAULT NULL,
    p_status VARCHAR DEFAULT NULL
)
RETURNS NUMERIC
LANGUAGE SQL
STABLE
AS $$
    SELECT COALESCE(SUM(st.revenue), 0)
    FROM sales_transactions st
    JOIN products p
        ON p.product_id = st.product_id
    WHERE
        (p_region IS NULL OR st.region = p_region)
        AND
        (p_category IS NULL OR p.category = p_category)
        AND
        (p_status IS NULL OR st.status = p_status);
$$;

-- AVERAGE equivalent.
CREATE OR REPLACE FUNCTION dax_average_revenue(
    p_region VARCHAR DEFAULT NULL
)
RETURNS NUMERIC
LANGUAGE SQL
STABLE
AS $$
    SELECT AVG(revenue)
    FROM sales_transactions
    WHERE p_region IS NULL
       OR region = p_region;
$$;

-- COUNT equivalent: counts non-NULL numeric values.
CREATE OR REPLACE FUNCTION dax_count_revenue(
    p_region VARCHAR DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE SQL
STABLE
AS $$
    SELECT COUNT(revenue)
    FROM sales_transactions
    WHERE p_region IS NULL
       OR region = p_region;
$$;

-- DISTINCTCOUNT equivalent.
-- COUNT(DISTINCT column) ignores NULL, so the additional
-- Boolean expression counts NULL as one distinct blank.
CREATE OR REPLACE FUNCTION dax_distinct_customer_count(
    p_region VARCHAR DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE SQL
STABLE
AS $$
    SELECT
        COUNT(DISTINCT customer_id)
        +
        CASE
            WHEN COUNT(*) FILTER (
                WHERE customer_id IS NULL
            ) > 0 THEN 1
            ELSE 0
        END
    FROM sales_transactions
    WHERE p_region IS NULL
       OR region = p_region;
$$;

-- ============================================================================
-- 6. FILTER EVALUATION
-- ============================================================================

-- Returns filtered transaction rows.
CREATE OR REPLACE FUNCTION dax_filter_transactions(
    p_min_revenue NUMERIC,
    p_region VARCHAR DEFAULT NULL,
    p_status VARCHAR DEFAULT NULL
)
RETURNS TABLE (
    transaction_id BIGINT,
    order_date DATE,
    region VARCHAR,
    category VARCHAR,
    revenue NUMERIC,
    status VARCHAR
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        st.transaction_id,
        st.order_date,
        st.region,
        p.category,
        st.revenue,
        st.status
    FROM sales_transactions st
    JOIN products p
        ON p.product_id = st.product_id
    WHERE
        st.revenue IS NOT NULL
        AND st.revenue >= p_min_revenue
        AND (p_region IS NULL OR st.region = p_region)
        AND (p_status IS NULL OR st.status = p_status);
$$;

-- ============================================================================
-- 7. CALCULATE EQUIVALENT
-- ============================================================================

/*
CALCULATE changes the analytical filter context.

This function accepts:
- Existing region filter
- Replacement region filter
- Category filter
- Status filter

The replacement region takes precedence over the existing region.

This models ordinary Boolean filter arguments, not every
advanced DAX filter-modifier or relationship behavior.
*/

CREATE OR REPLACE FUNCTION dax_calculate_revenue(
    p_existing_region VARCHAR DEFAULT NULL,
    p_replacement_region VARCHAR DEFAULT NULL,
    p_category VARCHAR DEFAULT NULL,
    p_status VARCHAR DEFAULT NULL
)
RETURNS NUMERIC
LANGUAGE SQL
STABLE
AS $$
    SELECT COALESCE(SUM(st.revenue), 0)
    FROM sales_transactions st
    JOIN products p
        ON p.product_id = st.product_id
    WHERE
        (
            COALESCE(
                p_replacement_region,
                p_existing_region
            ) IS NULL
            OR st.region = COALESCE(
                p_replacement_region,
                p_existing_region
            )
        )
        AND
        (p_category IS NULL OR p.category = p_category)
        AND
        (p_status IS NULL OR st.status = p_status);
$$;

-- ============================================================================
-- 8. ANALYTICAL VIEWS
-- ============================================================================

CREATE OR REPLACE VIEW v_sales_analytical_detail AS
SELECT
    st.transaction_id,
    st.order_date,
    EXTRACT(YEAR FROM st.order_date)::INTEGER AS sales_year,
    EXTRACT(MONTH FROM st.order_date)::INTEGER AS sales_month,
    st.customer_id,
    c.customer_name,
    c.customer_segment,
    st.product_id,
    p.product_name,
    p.category,
    st.region,
    st.quantity,
    st.unit_price,
    st.revenue,
    st.status
FROM sales_transactions st
JOIN products p
    ON p.product_id = st.product_id
LEFT JOIN customers c
    ON c.customer_id = st.customer_id;

CREATE OR REPLACE VIEW v_regional_sales_summary AS
SELECT
    region,
    COUNT(*) AS transaction_rows,
    COUNT(revenue) AS revenue_value_count,
    SUM(revenue) AS total_revenue,
    AVG(revenue) AS average_revenue,
    COUNT(DISTINCT customer_id) AS distinct_nonblank_customers,
    COUNT(*) FILTER (
        WHERE customer_id IS NULL
    ) AS blank_customer_rows
FROM sales_transactions
GROUP BY region;

CREATE OR REPLACE VIEW v_category_sales_summary AS
SELECT
    p.category,
    COUNT(*) AS transaction_rows,
    SUM(st.quantity) AS total_quantity,
    SUM(st.revenue) AS total_revenue,
    AVG(st.revenue) AS average_revenue,
    COUNT(st.revenue) AS revenue_count
FROM sales_transactions st
JOIN products p
    ON p.product_id = st.product_id
GROUP BY p.category;

-- ============================================================================
-- 9. VALIDATION REPORT
-- ============================================================================

CREATE OR REPLACE FUNCTION dax_validation_report()
RETURNS TABLE (
    validation_name TEXT,
    validation_result TEXT,
    observed_value NUMERIC
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        'TOTAL_REVENUE',
        CASE
            WHEN SUM(revenue) = 6600
            THEN 'PASS'
            ELSE 'FAIL'
        END,
        SUM(revenue)
    FROM sales_transactions

    UNION ALL

    SELECT
        'NONBLANK_REVENUE_COUNT',
        CASE
            WHEN COUNT(revenue) = 9
            THEN 'PASS'
            ELSE 'FAIL'
        END,
        COUNT(revenue)::NUMERIC
    FROM sales_transactions

    UNION ALL

    SELECT
        'DISTINCT_CUSTOMERS_INCLUDING_BLANK',
        CASE
            WHEN COUNT(DISTINCT customer_id)
                 +
                 CASE WHEN COUNT(*) FILTER (
                     WHERE customer_id IS NULL
                 ) > 0 THEN 1 ELSE 0 END = 7
            THEN 'PASS'
            ELSE 'FAIL'
        END,
        (
            COUNT(DISTINCT customer_id)
            +
            CASE WHEN COUNT(*) FILTER (
                WHERE customer_id IS NULL
            ) > 0 THEN 1 ELSE 0 END
        )::NUMERIC
    FROM sales_transactions;
$$;

