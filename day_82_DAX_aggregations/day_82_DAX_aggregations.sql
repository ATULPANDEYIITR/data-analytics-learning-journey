===============================================================================
DAX AGGREGATIONS: POSTGRESQL ANALYTICAL MODEL
===============================================================================

Implements relational equivalents of:

SUM
AVERAGE
COUNT
DISTINCTCOUNT
CALCULATE
FILTER

Business scenario:
Retail sales analysis across transactions, products, customers,
regions, categories, and reporting periods.

PostgreSQL version: 14+

Execute:
    psql -U postgres -d your_database -f dax_aggregations.sql

The script creates a dedicated schema and its analytical objects.
*/

