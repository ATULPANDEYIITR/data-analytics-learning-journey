-- ============================================================================
-- 14. CTE-BASED ANALYTICAL EVALUATION
-- ============================================================================

WITH transaction_metrics AS (
    SELECT
        region,
        COUNT(*) AS transaction_rows,
        COUNT(revenue) AS valid_revenue_rows,
        SUM(revenue) AS total_revenue,
        AVG(revenue) AS average_revenue,
        MAX(revenue) AS maximum_transaction
    FROM sales_transactions
    GROUP BY region
),
ranked_regions AS (
    SELECT
        *,
        RANK() OVER (
            ORDER BY total_revenue DESC NULLS LAST
        ) AS revenue_rank
    FROM transaction_metrics
)
SELECT *
FROM ranked_regions
ORDER BY revenue_rank;

-- ============================================================================
-- 15. TIME-BASED AGGREGATION
-- ============================================================================

SELECT
    DATE_TRUNC('month', order_date)::DATE AS sales_month,
    SUM(revenue) AS monthly_revenue,
    AVG(revenue) AS monthly_average,
    COUNT(revenue) AS revenue_transactions
FROM sales_transactions
GROUP BY DATE_TRUNC('month', order_date)
ORDER BY sales_month;

-- ============================================================================
-- 16. EDGE-CASE EVALUATION
-- ============================================================================

-- Empty result: SUM returns NULL in native PostgreSQL.
-- The DAX-style function returns zero through COALESCE.
SELECT
    SUM(revenue) AS native_postgresql_sum,
    COALESCE(SUM(revenue), 0) AS zero_default_sum,
    AVG(revenue) AS empty_average,
    COUNT(revenue) AS empty_count,
    COUNT(DISTINCT customer_id) AS empty_distinct_count
FROM sales_transactions
WHERE region = 'Antarctica';

-- Compare COUNT(*) and COUNT(column).
SELECT
    COUNT(*) AS transaction_rows,
    COUNT(revenue) AS nonblank_revenue_values,
    COUNT(customer_id) AS nonblank_customer_values,
    COUNT(*) FILTER (
        WHERE revenue IS NULL
    ) AS blank_revenue_rows
FROM sales_transactions;

-- ============================================================================
-- 17. ELIGIBILITY AND BUSINESS RULE EVALUATION
-- ============================================================================

/*
A reporting rule can restrict revenue calculations to completed
transactions and selected regions.

This is a business-level reporting condition, not a modification
of the underlying transaction records.
*/

WITH eligible_sales AS (
    SELECT
        st.transaction_id,
        st.region,
        st.revenue,
        p.category
    FROM sales_transactions st
    JOIN products p
        ON p.product_id = st.product_id
    WHERE
        st.status = 'Completed'
        AND st.revenue IS NOT NULL
        AND st.region IN ('North', 'South', 'East', 'West')
),
eligible_metrics AS (
    SELECT
        region,
        category,
        COUNT(*) AS eligible_transaction_count,
        SUM(revenue) AS eligible_revenue
    FROM eligible_sales
    GROUP BY region, category
)
SELECT *
FROM eligible_metrics
ORDER BY region, category;

