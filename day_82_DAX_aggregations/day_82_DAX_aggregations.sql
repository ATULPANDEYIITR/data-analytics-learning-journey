/*
===============================================================================
IMPLEMENTATION NOTES
===============================================================================

1. SUM ignores NULL values.
2. AVERAGE ignores NULL values.
3. COUNT(column) counts non-NULL values.
4. COUNT(*) counts rows.
5. COUNT(DISTINCT column) ignores NULL in PostgreSQL.
6. DAX DISTINCTCOUNT includes BLANK when present.
7. CALCULATE modifies filter context.
8. Ordinary CALCULATE Boolean filters replace existing filters
   on the same column unless the filter context is explicitly
   preserved through an appropriate modifier.
9. FILTER produces a row subset satisfying a condition.
10. Database indexes improve selective access but may not help
    every aggregation or low-selectivity query.

The SQL functions provide a controlled subset of DAX behavior.
They do not implement the complete DAX formula engine,
relationship propagation, row context, context transition,
ALL, ALLEXCEPT, ALLSELECTED, or calculation groups.
===============================================================================
*/
