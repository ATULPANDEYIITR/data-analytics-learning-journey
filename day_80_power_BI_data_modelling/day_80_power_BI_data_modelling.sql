-- Total sales.
SELECT
    SUM(sales_amount) AS total_sales
FROM fact_sales;

-- Total quantity and distinct orders.
SELECT
    SUM(quantity) AS total_quantity,
    COUNT(DISTINCT order_id) AS distinct_orders,
    COUNT(*) AS order_lines
FROM fact_sales;

-- Average order value.
-- Aggregate order lines before calculating the average.
WITH order_totals AS (
    SELECT
        order_id,
        SUM(sales_amount) AS order_amount
    FROM fact_sales
    GROUP BY order_id
)
SELECT
    ROUND(AVG(order_amount), 2) AS average_order_value
FROM order_totals;

-- Sales by product category.
SELECT
    category,
    SUM(sales_amount) AS total_sales,
    SUM(quantity) AS units_sold
FROM vw_sales_enriched
GROUP BY category
ORDER BY total_sales DESC;

-- Sales by customer region.
SELECT
    customer_region,
    SUM(sales_amount) AS total_sales
FROM vw_sales_enriched
GROUP BY customer_region
ORDER BY total_sales DESC;

-- Sales by calendar month.
SELECT *
FROM vw_sales_by_month
