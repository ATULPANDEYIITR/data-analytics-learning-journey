-- ============================================================================
-- 10. FACT-LEVEL VALIDATION TRIGGER
-- Foreign keys already enforce referential integrity.
-- This trigger prevents logically invalid transaction records.
-- ============================================================================

CREATE OR REPLACE FUNCTION validate_sales_fact()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.quantity <= 0 THEN
        RAISE EXCEPTION
            'Quantity must be greater than zero';
    END IF;

    IF NEW.unit_price < 0 OR NEW.discount_amount < 0 THEN
        RAISE EXCEPTION
            'Price and discount cannot be negative';
    END IF;

    IF NEW.discount_amount >
       NEW.quantity * NEW.unit_price THEN
        RAISE EXCEPTION
            'Discount cannot exceed gross line value';
    END IF;

    IF NEW.sales_amount <>
       ROUND(
           NEW.quantity * NEW.unit_price - NEW.discount_amount,
           2
       ) THEN
        RAISE EXCEPTION
            'Incorrect sales amount calculation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_sales_fact
BEFORE INSERT OR UPDATE ON fact_sales
FOR EACH ROW
EXECUTE FUNCTION validate_sales_fact();

-- ============================================================================
-- 11. VALIDATE RELATIONSHIP METADATA
-- The fact-side column is checked against the dimension-side key.
-- ============================================================================

CREATE OR REPLACE FUNCTION validate_model_relationships()
RETURNS TABLE (
    relationship_name VARCHAR,
    validation_result TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    relationship_record RECORD;
    duplicate_count BIGINT;
    orphan_count BIGINT;
    source_sql TEXT;
    target_sql TEXT;
BEGIN
    FOR relationship_record IN
        SELECT *
        FROM model_relationships
        WHERE is_active = TRUE
    LOOP
        IF relationship_record.cardinality = 'MANY_TO_MANY' THEN
            relationship_name :=
                relationship_record.relationship_name;

            validation_result :=
                'REVIEW: explicit bridge table required';

            RETURN NEXT;
            CONTINUE;
        END IF;

        source_sql := format(
            'SELECT COUNT(*) FROM (
                SELECT %I
                FROM %I
                GROUP BY %I
                HAVING COUNT(*) > 1
            ) duplicates',
            relationship_record.from_column,
            relationship_record.from_table,
            relationship_record.from_column
        );

        target_sql := format(
            'SELECT COUNT(*) FROM (
                SELECT %I
                FROM %I
                GROUP BY %I
                HAVING COUNT(*) > 1
            ) duplicates',
            relationship_record.to_column,
            relationship_record.to_table,
            relationship_record.to_column
        );

        IF relationship_record.cardinality IN (
            'MANY_TO_ONE',
            'ONE_TO_ONE'
        ) THEN
            EXECUTE target_sql INTO duplicate_count;

            IF duplicate_count > 0 THEN
                relationship_name :=
                    relationship_record.relationship_name;

                validation_result :=
                    'FAILED: duplicate dimension-side key';

                RETURN NEXT;
                CONTINUE;
            END IF;
        END IF;

        IF relationship_record.cardinality IN (
            'ONE_TO_MANY',
            'ONE_TO_ONE'
        ) THEN
            EXECUTE source_sql INTO duplicate_count;

            IF duplicate_count > 0 THEN
                relationship_name :=
                    relationship_record.relationship_name;

                validation_result :=
                    'FAILED: duplicate source-side key';

                RETURN NEXT;
                CONTINUE;
            END IF;
        END IF;

        EXECUTE format(
            'SELECT COUNT(*)
             FROM %I source
             LEFT JOIN %I target
               ON source.%I = target.%I
             WHERE source.%I IS NOT NULL
               AND target.%I IS NULL',
            relationship_record.from_table,
            relationship_record.to_table,
            relationship_record.from_column,
            relationship_record.to_column,
            relationship_record.from_column,
            relationship_record.to_column
        )
        INTO orphan_count;

        relationship_name :=
            relationship_record.relationship_name;

        IF orphan_count > 0 THEN
            validation_result :=
                'FAILED: orphan foreign keys = ' ||
                orphan_count::TEXT;
        ELSE
            validation_result := 'PASSED';
        END IF;

        RETURN NEXT;
    END LOOP;
END;
$$;

-- ============================================================================
-- 12. MODEL PUBLICATION FUNCTION
-- ============================================================================

CREATE OR REPLACE FUNCTION publish_model(
    p_model_name VARCHAR,
    p_version INTEGER
)
RETURNS TABLE (
    result_status model_status,
    error_count INTEGER,
    result_message TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    total_errors INTEGER;
BEGIN
    IF p_version <= 0 THEN
        RAISE EXCEPTION 'Version must be positive';
    END IF;

    INSERT INTO model_publication (
        model_name,
        version_number,
        status
    )
    VALUES (
        p_model_name,
        p_version,
        'DRAFT'
    );

    SELECT COUNT(*)
    INTO total_errors
    FROM validate_model_relationships()
    WHERE validation_result <> 'PASSED';

    IF total_errors > 0 THEN
        UPDATE model_publication
        SET status = 'FAILED',
            validation_errors = total_errors
        WHERE model_name = p_model_name
          AND version_number = p_version;

        result_status := 'FAILED';
        error_count := total_errors;
        result_message := 'Model publication rejected';

        RETURN NEXT;
        RETURN;
    END IF;

    UPDATE model_publication
    SET status = 'PUBLISHED',
        validation_errors = 0,
        published_at = CURRENT_TIMESTAMP
    WHERE model_name = p_model_name
      AND version_number = p_version;

    result_status := 'PUBLISHED';
    error_count := 0;
    result_message := 'Model published successfully';

    RETURN NEXT;

EXCEPTION
    WHEN unique_violation THEN
        RAISE EXCEPTION
            'Model version already exists: %.%',
            p_model_name,
            p_version;
END;
$$;

