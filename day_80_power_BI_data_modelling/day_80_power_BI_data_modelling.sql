CREATE OR REPLACE VIEW vw_sales_enriched AS
SELECT
    f.sales_key,
    f.order_id,
    f.order_line_number,

    d.full_date,
    d.calendar_year,
    d.calendar_month,
    d.month_name,
    d.calendar_quarter,

    p.product_code,
    p.product_name,
    p.category,
    p.subcategory,
    p.brand,

    c.customer_code,
    c.customer_name,
    c.region AS customer_region,
    c.city AS customer_city,
    c.customer_segment,

    s.store_name,
    s.city AS store_city,
    s.region AS store_region,

    f.quantity,
    f.unit_price,
    f.discount_amount,
    f.sales_amount,
    f.cost_amount,

    f.sales_amount - f.cost_amount AS gross_profit

FROM fact_sales f
JOIN dim_date d
    ON f.order_date_key = d.date_key
JOIN dim_product p
    ON f.product_key = p.product_key
JOIN dim_customer c
    ON f.customer_key = c.customer_key
JOIN dim_store s
    ON f.store_key = s.store_key;

CREATE OR REPLACE VIEW vw_sales_by_product AS
SELECT
    p.product_key,
    p.product_name,
    p.category,
    p.brand,

    COUNT(DISTINCT f.order_id) AS distinct_orders,
    SUM(f.quantity) AS units_sold,
    SUM(f.sales_amount) AS total_sales,
    SUM(f.cost_amount) AS total_cost,
    SUM(f.sales_amount - f.cost_amount) AS gross_profit

FROM dim_product p
LEFT JOIN fact_sales f
    ON p.product_key = f.product_key

GROUP BY
    p.product_key,
    p.product_name,
    p.category,
    p.brand;

CREATE OR REPLACE VIEW vw_sales_by_region AS
SELECT
    c.region,
    c.customer_segment,
    COUNT(DISTINCT f.order_id) AS distinct_orders,
    SUM(f.sales_amount) AS total_sales,
    SUM(f.quantity) AS units_sold

FROM dim_customer c
LEFT JOIN fact_sales f
    ON c.customer_key = f.customer_key

GROUP BY
    c.region,
    c.customer_segment;

CREATE OR REPLACE VIEW vw_sales_by_month AS
SELECT
    d.calendar_year,
    d.calendar_month,
    d.month_name,
    SUM(f.sales_amount) AS total_sales,
    SUM(f.quantity) AS units_sold

FROM dim_date d
LEFT JOIN fact_sales f
    ON d.date_key = f.order_date_key

GROUP BY
    d.calendar_year,
    d.calendar_month,
    d.month_name;

