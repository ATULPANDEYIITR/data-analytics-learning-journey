    (SELECT COUNT(*) FROM dim_customer) AS customer_dimension_rows,

    (SELECT COUNT(*) FROM dim_date) AS date_dimension_rows,

    (SELECT COUNT(*) FROM dim_store) AS store_dimension_rows,

    (SELECT COUNT(*) FROM model_relationships
     WHERE is_active = TRUE) AS active_relationships,

    (SELECT COUNT(*) FROM fact_sales
     WHERE ship_date_key IS NULL) AS missing_ship_dates;

