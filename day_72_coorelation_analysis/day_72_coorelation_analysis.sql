/*
Correlation Analysis Database
PostgreSQL 14+

Implements:
- Dataset management
- Paired numerical observations
- Pearson correlation
- Spearman rank correlation
- Kendall tau-b
- Partial correlation
- Sample-size validation
- Permutation-test result storage
- Analytical reporting
- Audit records
- Transaction-safe analysis processing
*/

CREATE SCHEMA IF NOT EXISTS correlation_lab;

SET search_path TO correlation_lab, public;

-- ============================================================
-- 1. DOMAIN TABLES
-- ============================================================

CREATE TABLE IF NOT EXISTS datasets (
    dataset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    dataset_name VARCHAR(150) NOT NULL UNIQUE,

    description TEXT NOT NULL,

    source_type VARCHAR(30) NOT NULL DEFAULT 'SIMULATED'
        CHECK (
            source_type IN (
                'SIMULATED',
                'OBSERVATIONAL',
                'EXPERIMENTAL',
                'TIME_SERIES'
            )
        ),

    minimum_sample_size INTEGER NOT NULL DEFAULT 3
        CHECK (minimum_sample_size >= 3),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    dataset_id BIGINT NOT NULL
        REFERENCES datasets(dataset_id)
        ON DELETE CASCADE,

    observation_number INTEGER NOT NULL
        CHECK (observation_number > 0),

    x_value DOUBLE PRECISION,

    y_value DOUBLE PRECISION,

    confounder_value DOUBLE PRECISION,

    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dataset_observation
        UNIQUE (dataset_id, observation_number),

    CONSTRAINT valid_x
        CHECK (
            x_value IS NULL OR
            x_value NOT IN (
                'Infinity'::DOUBLE PRECISION,
                '-Infinity'::DOUBLE PRECISION,
                'NaN'::DOUBLE PRECISION
            )
        ),

    CONSTRAINT valid_y
        CHECK (
            y_value IS NULL OR
            y_value NOT IN (
                'Infinity'::DOUBLE PRECISION,
                '-Infinity'::DOUBLE PRECISION,
                'NaN'::DOUBLE PRECISION
            )
        ),

    CONSTRAINT valid_confounder
        CHECK (
            confounder_value IS NULL OR
            confounder_value NOT IN (
                'Infinity'::DOUBLE PRECISION,
                '-Infinity'::DOUBLE PRECISION,
                'NaN'::DOUBLE PRECISION
            )
        )
);


CREATE TABLE IF NOT EXISTS analysis_runs (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    dataset_id BIGINT NOT NULL
        REFERENCES datasets(dataset_id),

    analysis_status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED'
        CHECK (
            analysis_status IN (
                'COMPLETED',
                'REJECTED',
                'FAILED'
            )
        ),

    minimum_required INTEGER NOT NULL,

    valid_sample_size INTEGER NOT NULL DEFAULT 0,

    initiated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    completed_at TIMESTAMPTZ,

    error_message TEXT,

    CHECK (minimum_required >= 3),

    CHECK (valid_sample_size >= 0)
);


CREATE TABLE IF NOT EXISTS correlation_results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    analysis_id BIGINT NOT NULL
        REFERENCES analysis_runs(analysis_id)
        ON DELETE CASCADE,

    method VARCHAR(20) NOT NULL
        CHECK (
            method IN (
                'PEARSON',
                'SPEARMAN',
                'KENDALL',
                'PARTIAL_PEARSON'
            )
        ),

    coefficient DOUBLE PRECISION,

    sample_size BIGINT NOT NULL,

    interpretation TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (analysis_id, method),

    CHECK (sample_size >= 0),

    CHECK (
        coefficient IS NULL OR
        (
            coefficient BETWEEN -1 AND 1
            AND coefficient NOT IN (
                'Infinity'::DOUBLE PRECISION,
                '-Infinity'::DOUBLE PRECISION,
                'NaN'::DOUBLE PRECISION
            )
        )
    )
);


CREATE TABLE IF NOT EXISTS permutation_results (
    permutation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    analysis_id BIGINT NOT NULL
        REFERENCES analysis_runs(analysis_id)
        ON DELETE CASCADE,

    observed_coefficient DOUBLE PRECISION NOT NULL,

    estimated_p_value DOUBLE PRECISION NOT NULL
        CHECK (estimated_p_value BETWEEN 0 AND 1),

    permutation_count INTEGER NOT NULL
        CHECK (permutation_count >= 100),

    significance_level DOUBLE PRECISION NOT NULL DEFAULT 0.05
        CHECK (
            significance_level > 0
            AND significance_level < 1
        ),

    significant BOOLEAN NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 2. INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_observations_dataset
    ON observations(dataset_id);

CREATE INDEX IF NOT EXISTS idx_observations_dataset_number
    ON observations(dataset_id, observation_number);

CREATE INDEX IF NOT EXISTS idx_analysis_dataset_date
    ON analysis_runs(dataset_id, initiated_at DESC);

CREATE INDEX IF NOT EXISTS idx_correlation_method
    ON correlation_results(method, coefficient);


-- ============================================================
-- 3. AUDIT TRIGGER
-- ============================================================

CREATE TABLE IF NOT EXISTS observation_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    observation_id BIGINT NOT NULL,

    dataset_id BIGINT NOT NULL,

    operation VARCHAR(10) NOT NULL,

    old_x DOUBLE PRECISION,

    old_y DOUBLE PRECISION,

    new_x DOUBLE PRECISION,

    new_y DOUBLE PRECISION,

    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    changed_by TEXT NOT NULL DEFAULT CURRENT_USER
);


CREATE OR REPLACE FUNCTION audit_observation_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN

        INSERT INTO observation_audit (
            observation_id,
            dataset_id,
            operation,
            new_x,
            new_y
        )
        VALUES (
            NEW.observation_id,
            NEW.dataset_id,
            'INSERT',
            NEW.x_value,
            NEW.y_value
        );

        RETURN NEW;

    ELSIF TG_OP = 'UPDATE' THEN

        INSERT INTO observation_audit (
            observation_id,
            dataset_id,
            operation,
            old_x,
            old_y,
            new_x,
            new_y
        )
        VALUES (
            NEW.observation_id,
            NEW.dataset_id,
            'UPDATE',
            OLD.x_value,
            OLD.y_value,
            NEW.x_value,
            NEW.y_value
        );

        RETURN NEW;

    ELSIF TG_OP = 'DELETE' THEN

        INSERT INTO observation_audit (
            observation_id,
            dataset_id,
            operation,
            old_x,
            old_y
        )
        VALUES (
            OLD.observation_id,
            OLD.dataset_id,
            'DELETE',
            OLD.x_value,
            OLD.y_value
        );

        RETURN OLD;
    END IF;

    RETURN NULL;
END;
$$;


DROP TRIGGER IF EXISTS trg_observation_audit
ON observations;

CREATE TRIGGER trg_observation_audit
AFTER INSERT OR UPDATE OR DELETE
ON observations
FOR EACH ROW
EXECUTE FUNCTION audit_observation_change();


-- ============================================================
-- 4. PEARSON AND SPEARMAN CALCULATION
-- ============================================================

CREATE OR REPLACE FUNCTION calculate_correlations(
    p_dataset_id BIGINT
)
RETURNS TABLE (
    method TEXT,
    coefficient DOUBLE PRECISION,
    sample_size BIGINT,
    interpretation TEXT
)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_minimum INTEGER;
    v_n BIGINT;
    v_pearson DOUBLE PRECISION;
    v_spearman DOUBLE PRECISION;
    v_kendall DOUBLE PRECISION;
BEGIN

    SELECT minimum_sample_size
    INTO v_minimum
    FROM datasets
    WHERE dataset_id = p_dataset_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Dataset % does not exist', p_dataset_id;
    END IF;

    SELECT COUNT(*)
    INTO v_n
    FROM observations
    WHERE dataset_id = p_dataset_id
      AND x_value IS NOT NULL
      AND y_value IS NOT NULL;

    IF v_n < v_minimum THEN
        RAISE EXCEPTION
            'Insufficient paired observations: required %, found %',
            v_minimum, v_n;
    END IF;

    -- Pearson measures linear association.
    SELECT corr(x_value, y_value)
    INTO v_pearson
    FROM observations
    WHERE dataset_id = p_dataset_id
      AND x_value IS NOT NULL
      AND y_value IS NOT NULL;

    -- Spearman is Pearson correlation applied to average ranks.
    WITH ranked AS (
        SELECT
            x_value,
            y_value,
            rank() OVER (ORDER BY x_value)
                + (
                    count(*) OVER (PARTITION BY x_value) - 1
                ) / 2.0 AS rank_x,

            rank() OVER (ORDER BY y_value)
                + (
                    count(*) OVER (PARTITION BY y_value) - 1
                ) / 2.0 AS rank_y
        FROM observations
        WHERE dataset_id = p_dataset_id
          AND x_value IS NOT NULL
          AND y_value IS NOT NULL
    )
    SELECT corr(rank_x, rank_y)
    INTO v_spearman
    FROM ranked;

    -- Kendall tau-b uses concordant and discordant pairs.
    -- Pair comparison is O(n^2).
    WITH pairs AS (
        SELECT
            CASE
                WHEN a.x_value = b.x_value
                 AND a.y_value = b.y_value
                    THEN 'BOTH_TIED'

                WHEN a.x_value = b.x_value
                    THEN 'X_TIED'

                WHEN a.y_value = b.y_value
                    THEN 'Y_TIED'

                WHEN
                    (a.x_value > b.x_value AND a.y_value > b.y_value)
                    OR
                    (a.x_value < b.x_value AND a.y_value < b.y_value)
                    THEN 'CONCORDANT'

                ELSE 'DISCORDANT'
            END AS pair_type

        FROM observations a

        JOIN observations b
          ON a.dataset_id = b.dataset_id
         AND a.observation_id < b.observation_id

        WHERE a.dataset_id = p_dataset_id
          AND a.x_value IS NOT NULL
          AND a.y_value IS NOT NULL
          AND b.x_value IS NOT NULL
          AND b.y_value IS NOT NULL
    ),
    counts AS (
        SELECT
            count(*) FILTER (
                WHERE pair_type = 'CONCORDANT'
            ) AS concordant,

            count(*) FILTER (
                WHERE pair_type = 'DISCORDANT'
            ) AS discordant,

            count(*) FILTER (
                WHERE pair_type = 'X_TIED'
            ) AS ties_x,

            count(*) FILTER (
                WHERE pair_type = 'Y_TIED'
            ) AS ties_y

        FROM pairs
    )
    SELECT
        CASE
            WHEN
                (concordant + discordant + ties_x) = 0
                OR
                (concordant + discordant + ties_y) = 0
                THEN NULL

            ELSE
                (concordant - discordant)::DOUBLE PRECISION
                /
                sqrt(
                    (concordant + discordant + ties_x)::DOUBLE PRECISION
                    *
                    (concordant + discordant + ties_y)::DOUBLE PRECISION
                )
        END
    INTO v_kendall
    FROM counts;

    RETURN QUERY
    SELECT
        'PEARSON'::TEXT,
        v_pearson,
        v_n,
        CASE
            WHEN abs(v_pearson) >= 0.70 THEN 'Very strong'
            WHEN abs(v_pearson) >= 0.50 THEN 'Strong'
            WHEN abs(v_pearson) >= 0.30 THEN 'Moderate'
            WHEN abs(v_pearson) >= 0.10 THEN 'Weak'
            ELSE 'Negligible'
        END::TEXT

    UNION ALL

    SELECT
        'SPEARMAN'::TEXT,
        v_spearman,
        v_n,
        'Monotonic rank association'::TEXT

    UNION ALL

    SELECT
        'KENDALL'::TEXT,
        v_kendall,
        v_n,
        'Ordinal concordance using tau-b'::TEXT;

END;
$$;


-- ============================================================
-- 5. PARTIAL PEARSON CORRELATION
-- ============================================================

CREATE OR REPLACE FUNCTION calculate_partial_correlation(
    p_dataset_id BIGINT
)
RETURNS TABLE (
    coefficient DOUBLE PRECISION,
    sample_size BIGINT
)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_n BIGINT;
    v_minimum INTEGER;
    v_xz DOUBLE PRECISION;
    v_yz DOUBLE PRECISION;
    v_xy DOUBLE PRECISION;
BEGIN

    SELECT minimum_sample_size
    INTO v_minimum
    FROM datasets
    WHERE dataset_id = p_dataset_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Dataset does not exist.';
    END IF;

    SELECT
        COUNT(*),
        corr(x_value, confounder_value),
        corr(y_value, confounder_value),
        corr(x_value, y_value)
    INTO
        v_n,
        v_xz,
        v_yz,
        v_xy
    FROM observations
    WHERE dataset_id = p_dataset_id
      AND x_value IS NOT NULL
      AND y_value IS NOT NULL
      AND confounder_value IS NOT NULL;

    IF v_n < v_minimum THEN
        RAISE EXCEPTION
            'Insufficient complete observations for partial correlation.';
    END IF;

    IF v_xz IS NULL OR v_yz IS NULL OR v_xy IS NULL THEN
        RAISE EXCEPTION
            'Partial correlation is undefined for constant variables.';
    END IF;

    IF abs(v_xz) >= 1 OR abs(v_yz) >= 1 THEN
        RAISE EXCEPTION
            'Degenerate confounder relationship.';
    END IF;

    RETURN QUERY
    SELECT
        (
            v_xy - v_xz * v_yz
        ) / sqrt(
            (1 - v_xz * v_xz) *
            (1 - v_yz * v_yz)
        ),
        v_n;

END;
$$;


-- ============================================================
-- 6. ANALYSIS PROCESSING PROCEDURE
-- ============================================================

CREATE OR REPLACE PROCEDURE process_dataset(
    p_dataset_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_analysis_id BIGINT;
    v_minimum INTEGER;
    v_n BIGINT;
    v_record RECORD;
BEGIN

    SELECT minimum_sample_size
    INTO v_minimum
    FROM datasets
    WHERE dataset_id = p_dataset_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Dataset not found: %', p_dataset_id;
    END IF;

    SELECT COUNT(*)
    INTO v_n
    FROM observations
    WHERE dataset_id = p_dataset_id
      AND x_value IS NOT NULL
      AND y_value IS NOT NULL;

    INSERT INTO analysis_runs (
        dataset_id,
        analysis_status,
        minimum_required,
        valid_sample_size
    )
    VALUES (
        p_dataset_id,
        CASE
            WHEN v_n >= v_minimum THEN 'COMPLETED'
            ELSE 'REJECTED'
        END,
        v_minimum,
        v_n
    )
    RETURNING analysis_id INTO v_analysis_id;

    IF v_n < v_minimum THEN

        UPDATE analysis_runs
        SET
            error_message = 'Insufficient paired observations.',
            completed_at = CURRENT_TIMESTAMP
        WHERE analysis_id = v_analysis_id;

        RETURN;
    END IF;

    FOR v_record IN
        SELECT *
        FROM calculate_correlations(p_dataset_id)
    LOOP

        INSERT INTO correlation_results (
            analysis_id,
            method,
            coefficient,
            sample_size,
            interpretation
        )
        VALUES (
            v_analysis_id,
            v_record.method,
            v_record.coefficient,
            v_record.sample_size,
            v_record.interpretation
        );

    END LOOP;

    UPDATE analysis_runs
    SET completed_at = CURRENT_TIMESTAMP
    WHERE analysis_id = v_analysis_id;

END;
$$;


-- ============================================================
-- 7. REPORTING VIEW
-- ============================================================

CREATE OR REPLACE VIEW correlation_report AS
SELECT
    d.dataset_name,
    d.source_type,
    a.analysis_id,
    a.analysis_status,
    a.valid_sample_size,
    r.method,
    r.coefficient,
    r.interpretation,
    a.initiated_at,
    a.completed_at
FROM analysis_runs a
JOIN datasets d
    ON d.dataset_id = a.dataset_id
LEFT JOIN correlation_results r
    ON r.analysis_id = a.analysis_id;


