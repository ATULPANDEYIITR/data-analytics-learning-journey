-- ============================================================
-- 10. RETRIEVAL
-- ============================================================

SELECT *
FROM correlation_report
ORDER BY dataset_name, analysis_id, method;


-- ============================================================
-- 11. VALIDATION
-- ============================================================

SELECT
    d.dataset_name,
    count(o.observation_id) AS total_observations,

    count(*) FILTER (
        WHERE o.x_value IS NOT NULL
          AND o.y_value IS NOT NULL
    ) AS valid_pairs,

    d.minimum_sample_size,

    CASE
        WHEN count(*) FILTER (
            WHERE o.x_value IS NOT NULL
              AND o.y_value IS NOT NULL
        ) >= d.minimum_sample_size
        THEN 'ELIGIBLE'
        ELSE 'REJECTED'
    END AS eligibility

FROM datasets d

LEFT JOIN observations o
    ON o.dataset_id = d.dataset_id

GROUP BY
    d.dataset_id,
    d.dataset_name,
    d.minimum_sample_size

ORDER BY d.dataset_name;


-- ============================================================
-- 12. AGGREGATION
-- ============================================================

SELECT
    method,
    count(*) AS analysis_count,
    avg(coefficient) AS average_coefficient,
    min(coefficient) AS minimum_coefficient,
    max(coefficient) AS maximum_coefficient
FROM correlation_results
WHERE coefficient IS NOT NULL
GROUP BY method
ORDER BY method;


-- ============================================================
-- 13. PARTIAL CORRELATION EVALUATION
-- ============================================================

SELECT
    d.dataset_name,
    p.coefficient,
    p.sample_size
FROM datasets d
CROSS JOIN LATERAL
    calculate_partial_correlation(d.dataset_id) p
WHERE d.dataset_name = 'confounding_demonstration';


-- ============================================================
-- 14. FAILURE AND QUALITY REPORTING
-- ============================================================

SELECT
    dataset_id,
    analysis_id,
    analysis_status,
    valid_sample_size,
    minimum_required,
    error_message,
    initiated_at
FROM analysis_runs
WHERE analysis_status <> 'COMPLETED'
   OR error_message IS NOT NULL
ORDER BY initiated_at DESC;


-- ============================================================
-- 15. AUDIT REPORT
-- ============================================================

SELECT
    observation_id,
    dataset_id,
    operation,
    old_x,
    old_y,
    new_x,
    new_y,
    changed_at,
    changed_by
FROM observation_audit
ORDER BY changed_at DESC;


-- ============================================================
-- 16. DATA QUALITY: CONSTANT VARIABLES
-- ============================================================

SELECT
    dataset_id,
    count(DISTINCT x_value) AS distinct_x,
    count(DISTINCT y_value) AS distinct_y,
    CASE
        WHEN count(DISTINCT x_value) <= 1
            THEN 'X IS CONSTANT'
        WHEN count(DISTINCT y_value) <= 1
            THEN 'Y IS CONSTANT'
        ELSE 'VARIABLES HAVE VARIATION'
    END AS data_quality_status
FROM observations
WHERE x_value IS NOT NULL
  AND y_value IS NOT NULL
GROUP BY dataset_id;


-- ============================================================
-- 17. REPRODUCIBLE QUERY FOR A SINGLE DATASET
-- ============================================================

SELECT
    method,
    coefficient,
    sample_size,
    interpretation
FROM calculate_correlations(
    (
        SELECT dataset_id
        FROM datasets
        WHERE dataset_name = 'linear_demonstration'
    )
)
ORDER BY method;
