-- Linear data.
INSERT INTO observations (
    dataset_id,
    observation_number,
    x_value,
    y_value
)
SELECT
    d.dataset_id,
    v.n,
    v.n::DOUBLE PRECISION,
    (2 * v.n)::DOUBLE PRECISION
FROM datasets d
CROSS JOIN generate_series(1, 6) AS v(n)
WHERE d.dataset_name = 'linear_demonstration'
ON CONFLICT (dataset_id, observation_number) DO NOTHING;


-- Nonlinear monotonic data.
INSERT INTO observations (
    dataset_id,
    observation_number,
    x_value,
    y_value
)
SELECT
    d.dataset_id,
    v.n,
    v.n::DOUBLE PRECISION,
    (v.n * v.n)::DOUBLE PRECISION
FROM datasets d
CROSS JOIN generate_series(1, 6) AS v(n)
WHERE d.dataset_name = 'monotonic_demonstration'
ON CONFLICT (dataset_id, observation_number) DO NOTHING;


-- Confounding scenario with a common driver.
