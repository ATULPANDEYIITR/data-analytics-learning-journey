-- Base analytical measure.
CREATE OR REPLACE VIEW v_daily_sales AS
SELECT
    d.calendar_date,
    d.calendar_year,
    d.calendar_quarter,
    d.calendar_month,
    d.year_month,
    COALESCE(SUM(f.total_amount), 0)::NUMERIC(18, 2) AS sales_amount
FROM dim_date d
LEFT JOIN fact_sales f
    ON f.transaction_date = d.calendar_date
GROUP BY
    d.calendar_date,
    d.calendar_year,
    d.calendar_quarter,
    d.calendar_month,
    d.year_month;


-- Month-level aggregation.
CREATE OR REPLACE VIEW v_monthly_sales AS
SELECT
    calendar_year,
    calendar_month,
    year_month,
    SUM(sales_amount)::NUMERIC(18, 2) AS monthly_sales
FROM v_daily_sales
GROUP BY
    calendar_year,
    calendar_month,
    year_month;


-- Previous-year comparison using the corresponding calendar date.
CREATE OR REPLACE VIEW v_year_over_year AS
WITH yearly_comparison AS (
    SELECT
        current_period.calendar_date,
        current_period.sales_amount AS current_sales,
        previous_period.sales_amount AS previous_year_sales
    FROM v_daily_sales current_period
    LEFT JOIN v_daily_sales previous_period
        ON previous_period.calendar_date =
           (current_period.calendar_date - INTERVAL '1 year')::DATE
)
SELECT
    calendar_date,
    current_sales,
    COALESCE(previous_year_sales, 0)::NUMERIC(18, 2)
        AS previous_year_sales,
    current_sales - COALESCE(previous_year_sales, 0)
        AS sales_difference,
    CASE
        WHEN COALESCE(previous_year_sales, 0) = 0 THEN NULL
        ELSE ROUND(
            (
                (current_sales - previous_year_sales)
                / previous_year_sales
            ) * 100,
            2
        )
    END AS percentage_change
FROM yearly_comparison;


-- Central function for date-context aggregation.
CREATE OR REPLACE FUNCTION sales_for_dates(
    p_start DATE,
    p_end DATE
)
RETURNS NUMERIC(18, 2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_total NUMERIC(18, 2);
BEGIN
    IF p_start IS NULL OR p_end IS NULL OR p_start > p_end THEN
        RAISE EXCEPTION 'Invalid date range: % to %', p_start, p_end;
    END IF;

    SELECT COALESCE(SUM(f.total_amount), 0)
    INTO v_total
    FROM fact_sales f
    WHERE f.transaction_date BETWEEN p_start AND p_end;

    RETURN v_total;
END;
$$;


-- DATEADD-style transformation.
CREATE OR REPLACE FUNCTION dateadd_period(
    p_date DATE,
    p_offset INTEGER,
    p_unit TEXT
)
RETURNS DATE
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_date IS NULL OR p_offset IS NULL THEN
        RAISE EXCEPTION 'Date and offset cannot be NULL.';
    END IF;

    CASE UPPER(p_unit)
        WHEN 'DAY' THEN
            RETURN p_date + p_offset;

        WHEN 'MONTH' THEN
            RETURN (p_date + (
                p_offset || ' months'
            )::INTERVAL)::DATE;

        WHEN 'YEAR' THEN
            RETURN (p_date + (
                p_offset || ' years'
            )::INTERVAL)::DATE;

        ELSE
            RAISE EXCEPTION 'Unsupported unit: %', p_unit;
    END CASE;
END;
$$;


-- Period-to-date calculation.
CREATE OR REPLACE FUNCTION period_to_date_sales(
    p_end_date DATE,
    p_period TEXT
)
RETURNS NUMERIC(18, 2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_start DATE;
BEGIN
    IF p_end_date IS NULL THEN
        RAISE EXCEPTION 'End date cannot be NULL.';
    END IF;

    CASE UPPER(p_period)
        WHEN 'MTD' THEN
            v_start := DATE_TRUNC('month', p_end_date)::DATE;

        WHEN 'QTD' THEN
            v_start := DATE_TRUNC('quarter', p_end_date)::DATE;

        WHEN 'YTD' THEN
            v_start := DATE_TRUNC('year', p_end_date)::DATE;

        ELSE
            RAISE EXCEPTION 'Unsupported period: %', p_period;
    END CASE;

    RETURN sales_for_dates(v_start, p_end_date);
END;
$$;


-- Rolling window includes its ending date.
CREATE OR REPLACE FUNCTION rolling_sales(
    p_end_date DATE,
    p_days INTEGER
)
RETURNS NUMERIC(18, 2)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_end_date IS NULL OR p_days IS NULL OR p_days <= 0 THEN
        RAISE EXCEPTION 'End date and positive days are required.';
    END IF;

    RETURN sales_for_dates(
        p_end_date - (p_days - 1),
        p_end_date
    );
END;
$$;


-- SAMEPERIODLASTYEAR-style comparison.
CREATE OR REPLACE FUNCTION same_period_last_year_sales(
    p_start DATE,
    p_end DATE
)
RETURNS NUMERIC(18, 2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_previous_start DATE;
    v_previous_end DATE;
BEGIN
    IF p_start IS NULL OR p_end IS NULL OR p_start > p_end THEN
        RAISE EXCEPTION 'Invalid comparison period.';
    END IF;

    v_previous_start := (p_start - INTERVAL '1 year')::DATE;
    v_previous_end := (p_end - INTERVAL '1 year')::DATE;

    RETURN sales_for_dates(
        v_previous_start,
        v_previous_end
    );
END;
$$;


-- Detailed report for a selected period.
CREATE OR REPLACE FUNCTION time_intelligence_report(
    p_start DATE,
    p_end DATE
)
RETURNS TABLE (
    metric TEXT,
    amount NUMERIC(18, 2)
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_start IS NULL OR p_end IS NULL OR p_start > p_end THEN
        RAISE EXCEPTION 'Invalid reporting period.';
    END IF;

    RETURN QUERY
    SELECT 'Current Period'::TEXT,
           sales_for_dates(p_start, p_end)

    UNION ALL

    SELECT 'Previous Year Period'::TEXT,
           same_period_last_year_sales(p_start, p_end)

    UNION ALL

    SELECT 'MTD'::TEXT,
           period_to_date_sales(
               p_end,
               'MTD'
           )

    UNION ALL

    SELECT 'QTD'::TEXT,
           period_to_date_sales(
               p_end,
               'QTD'
           )

    UNION ALL

    SELECT 'YTD'::TEXT,
           period_to_date_sales(
               p_end,
               'YTD'
           )

    UNION ALL

    SELECT 'Rolling 30 Days'::TEXT,
           rolling_sales(p_end, 30);
END;
$$;


-- Daily report with running YTD, MTD and QTD values.
CREATE OR REPLACE VIEW v_period_running_sales AS
SELECT
    calendar_date,
    sales_amount,

    SUM(sales_amount) OVER (
        PARTITION BY calendar_year
        ORDER BY calendar_date
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS ytd_sales,

    SUM(sales_amount) OVER (
        PARTITION BY calendar_year, calendar_month
        ORDER BY calendar_date
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS mtd_sales,

    SUM(sales_amount) OVER (
        PARTITION BY
            calendar_year,
            calendar_quarter
        ORDER BY calendar_date
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS qtd_sales

FROM v_daily_sales;


-- Rolling 30 calendar-day measure.
CREATE OR REPLACE VIEW v_rolling_30_day_sales AS
SELECT
    current_day.calendar_date,
    SUM(previous_days.sales_amount)::NUMERIC(18, 2)
        AS rolling_30_day_sales
FROM v_daily_sales current_day
JOIN v_daily_sales previous_days
    ON previous_days.calendar_date
       BETWEEN current_day.calendar_date - 29
           AND current_day.calendar_date
GROUP BY current_day.calendar_date;


-- Product and regional reporting.
CREATE OR REPLACE VIEW v_sales_by_product_region AS
SELECT
    p.product_name,
    p.category,
    r.region_name,
    SUM(f.total_amount)::NUMERIC(18, 2) AS total_sales,
    SUM(f.quantity) AS total_quantity,
    COUNT(*) AS transaction_count
FROM fact_sales f
JOIN dim_product p ON p.product_id = f.product_id
JOIN dim_region r ON r.region_id = f.region_id
GROUP BY
    p.product_name,
    p.category,
    r.region_name;


