-- A continuous date dimension is essential for reliable time intelligence.
CREATE TABLE IF NOT EXISTS dim_date (
    calendar_date DATE PRIMARY KEY,
    calendar_year INTEGER NOT NULL,
    calendar_quarter INTEGER NOT NULL,
    calendar_month INTEGER NOT NULL,
    month_name TEXT NOT NULL,
    year_month TEXT NOT NULL,
    day_of_year INTEGER NOT NULL,
    day_of_month INTEGER NOT NULL,
    is_weekend BOOLEAN NOT NULL,

    CONSTRAINT valid_quarter
        CHECK (calendar_quarter BETWEEN 1 AND 4),

    CONSTRAINT valid_month
        CHECK (calendar_month BETWEEN 1 AND 12),

    CONSTRAINT valid_year
        CHECK (calendar_year BETWEEN 1 AND 9999)
);

-- Generate three complete calendar years.
INSERT INTO dim_date (
    calendar_date,
    calendar_year,
    calendar_quarter,
    calendar_month,
    month_name,
    year_month,
    day_of_year,
    day_of_month,
    is_weekend
)
SELECT
    d::DATE,
    EXTRACT(YEAR FROM d)::INTEGER,
    EXTRACT(QUARTER FROM d)::INTEGER,
    EXTRACT(MONTH FROM d)::INTEGER,
    TO_CHAR(d, 'FMMonth'),
    TO_CHAR(d, 'YYYY-MM'),
    EXTRACT(DOY FROM d)::INTEGER,
    EXTRACT(DAY FROM d)::INTEGER,
    EXTRACT(ISODOW FROM d)::INTEGER IN (6, 7)
FROM GENERATE_SERIES(
    DATE '2024-01-01',
    DATE '2026-12-31',
    INTERVAL '1 day'
) AS series(d)
ON CONFLICT (calendar_date) DO NOTHING;


